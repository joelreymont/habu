\ ieee754-test.f - focused IEEE-754 bit and rounding tests.

require lib/test.f
require lib/ieee754.f

package IEEE754-TEST
private

: NEGATIVE-SHIFT ( -- )
   1 -1 IEEE754:ROUND-SHIFT-EVEN drop ;
: NEGATIVE-SIGNIFICAND ( -- )
   -1 1 IEEE754:ROUND-SHIFT-EVEN drop ;

: BIT-CASTS ( -- )
   1.0 IEEE754:F64>BITS $3FF0000000000000 T=
   $BFF8000000000000 IEEE754:BITS>F64 IEEE754:F64>BITS
      $BFF8000000000000 T=
   $8000000000000000 IEEE754:BITS>F64 IEEE754:F64>BITS
      $8000000000000000 T=
   $7FF8000000001234 IEEE754:BITS>F64 IEEE754:F64>BITS
      $7FF8000000001234 T= ;

: ROUNDING ( -- )
   $18 3 IEEE754:ROUND-SHIFT-EVEN 3 T=
   $13 3 IEEE754:ROUND-SHIFT-EVEN 2 T=
   $14 3 IEEE754:ROUND-SHIFT-EVEN 2 T=
   $15 3 IEEE754:ROUND-SHIFT-EVEN 3 T=
   $1C 3 IEEE754:ROUND-SHIFT-EVEN 4 T=
   $1D 3 IEEE754:ROUND-SHIFT-EVEN 4 T=
   $1234 0 IEEE754:ROUND-SHIFT-EVEN $1234 T=
   $4000000000000000 63 IEEE754:ROUND-SHIFT-EVEN 0 T=
   $7FFFFFFFFFFFFFFF 63 IEEE754:ROUND-SHIFT-EVEN 1 T=
   1 64 IEEE754:ROUND-SHIFT-EVEN 0 T=
   [: NEGATIVE-SHIFT ;] IEEE754:E-ROUND-DOMAIN TTHROWSQ
   [: NEGATIVE-SIGNIFICAND ;] IEEE754:E-ROUND-DOMAIN TTHROWSQ ;

public

: RUN ( -- )
   T-RESET
   BIT-CASTS
   ROUNDING
   T-REPORT ;

;package

IEEE754-TEST:RUN
