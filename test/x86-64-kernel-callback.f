package X64K-CB

DATA-START $20000 + constant ARGS
ARGS 8 CELL * + constant VALUES
VALUES 3 CELL * + constant XTS
XTS CELL + constant ROWS
ROWS CB-ROW-BYTES + constant INNER-ARGS
INNER-ARGS 8 CELL * + constant INNER-VALUES
INNER-VALUES 2 CELL * + constant NEST-DEPTH
NEST-DEPTH CELL + constant QSORT-FN
QSORT-FN CELL + constant THUNK

: DATA-REG ( -- X64ASM:r64 ) ENGINE-GPR:X64-RBASE X64ASM:>R64 ;
: N, ( n -- ) X64HARNESS:PUSH, ;
: ROW ( str -- ) X64HARNESS:CALL-ROW, ;
: ARG ( n -- n ) CELL * ARGS + ;

\ The checked dispatch ABI reads C's two pointer arguments through CB-FRAME
\ and writes a signed three-way comparison into its first integer result slot.
: COMPARE, ( -- )
   X64CODE:LBL {: compare:label :}
   X64ASM:RAX 1 X64ASM:>IMM32 X64CODE:ASM-SINK X64ASM:ENC-MOV-RI32  0 X64RT:G-PUSH
   0 X64RT:G-POP
   X64ASM:RAX DATA-REG NEST-DEPTH X64ASM:MEM-OFF X64CODE:ASM-SINK X64ASM:ENC-MOV-RM
   X64ASM:RAX X64ASM:RAX X64CODE:ASM-SINK X64ASM:ENC-TEST-RR  X64ASM:C-NE compare X64CODE:JCC,
   X64ASM:RAX 1 X64ASM:>IMM32 X64CODE:ASM-SINK X64ASM:ENC-MOV-RI32
   X64ASM:RAX DATA-REG NEST-DEPTH X64ASM:MEM-OFF X64CODE:ASM-SINK X64ASM:ENC-MOV-MR
   X64ASM:RAX DATA-REG INNER-ARGS X64ASM:MEM-OFF X64CODE:ASM-SINK X64ASM:ENC-LEA  0 X64RT:G-PUSH
   X64ASM:RAX 4 X64ASM:>IMM32 X64CODE:ASM-SINK X64ASM:ENC-MOV-RI32  0 X64RT:G-PUSH
   X64ASM:RAX DATA-REG QSORT-FN X64ASM:MEM-OFF X64CODE:ASM-SINK X64ASM:ENC-MOV-RM  0 X64RT:G-PUSH
   s" ffi-call" ROW  0 X64RT:G-POP
   X64ASM:RAX 2 X64ASM:>IMM32 X64CODE:ASM-SINK X64ASM:ENC-MOV-RI32
   X64ASM:RAX DATA-REG NEST-DEPTH X64ASM:MEM-OFF X64CODE:ASM-SINK X64ASM:ENC-MOV-MR
   compare X64CODE:LBL,
   X64ASM:RAX DATA-REG CB-FRAME X64ASM:MEM-OFF X64CODE:ASM-SINK X64ASM:ENC-MOV-RM
   X64ASM:RCX X64ASM:RAX X64ASM:MEM-AT X64CODE:ASM-SINK X64ASM:ENC-MOV-RM
   X64ASM:RDX X64ASM:RAX CELL X64ASM:MEM-OFF X64CODE:ASM-SINK X64ASM:ENC-MOV-RM
   X64ASM:RCX X64ASM:RCX X64ASM:MEM-AT X64CODE:ASM-SINK X64ASM:ENC-MOV-RM
   X64ASM:RDX X64ASM:RDX X64ASM:MEM-AT X64CODE:ASM-SINK X64ASM:ENC-MOV-RM
   X64ASM:RCX X64ASM:RDX X64CODE:ASM-SINK X64ASM:ENC-SUB-RR
   X64ASM:RCX X64ASM:RAX X64ASM:MEM-AT X64CODE:ASM-SINK X64ASM:ENC-MOV-MR ;

: SYM, ( str -- ) {: s:str :}
   X64CODE:LBL X64CODE:LBL {: name:label past:label :}
   past X64CODE:JMP,
   name X64CODE:LBL,  s X64CODE:ASM-SINK VEC:APPEND
   0 X64CODE:ASM-SINK VEC:PUSH c!
   past X64CODE:LBL,
   X64ASM:RSI name X64CODE:MOVABS,  X64KERNEL:DLSYM,  0 X64RT:G-PUSH ;

\ Leave in rax slot 0's C entry: mov r10, 0 and a jump to the thunk. C keeps its
\ own rbp, so the stub names the thunk's cell by its absolute address.
: STUB, ( -- )
   s" callback-entry" ROW  0 X64RT:G-POP
   X64ASM:RAX DATA-REG THUNK X64ASM:MEM-OFF X64CODE:ASM-SINK X64ASM:ENC-MOV-MR
   [: X64ASM:R10 0 X64ASM:>IMM32 X64CODE:ASM-SINK X64ASM:ENC-MOV-RI32
      X64ASM:RAX LINUX-LAYOUT:DATA-VA THUNK + X64ASM:>IMM64 X64CODE:ASM-SINK X64ASM:ENC-MOV-RI64
      X64ASM:RAX X64ASM:RAX X64ASM:MEM-AT X64CODE:ASM-SINK X64ASM:ENC-MOV-RM
      X64ASM:RAX X64CODE:ASM-SINK X64ASM:ENC-JMP-REG ;] X64HARNESS:ROUTINE,
   X64ASM:RAX swap X64CODE:MOVABS, ;

: SORT-CASE ( -- )
   [: COMPARE, ;] X64HARNESS:ROUTINE, XTS X64HARNESS:LABEL-CELL!,
   XTS CB-XTS X64HARNESS:DATA-ADDR!,
   ROWS CB-ROWS X64HARNESS:DATA-ADDR!,
   0 ROWS X64HARNESS:DATA-ADDR!,
   3 VALUES X64HARNESS:CELL!,
   1 VALUES CELL + X64HARNESS:CELL!,
   2 VALUES 2 CELL * + X64HARNESS:CELL!,
   2 INNER-VALUES X64HARNESS:CELL!,
   1 INNER-VALUES CELL + X64HARNESS:CELL!,
   INNER-VALUES INNER-ARGS X64HARNESS:DATA-ADDR!,
   2 INNER-ARGS CELL + X64HARNESS:CELL!,
   CELL INNER-ARGS 2 CELL * + X64HARNESS:CELL!,
   VALUES 0 ARG X64HARNESS:DATA-ADDR!,
   3 1 ARG X64HARNESS:CELL!,
   CELL 2 ARG X64HARNESS:CELL!,
   STUB,
   X64ASM:RAX DATA-REG 3 ARG X64ASM:MEM-OFF X64CODE:ASM-SINK X64ASM:ENC-MOV-MR
   X64ASM:RAX DATA-REG INNER-ARGS 3 CELL * + X64ASM:MEM-OFF X64CODE:ASM-SINK X64ASM:ENC-MOV-MR
   s" qsort" SYM,  0 X64RT:G-POP
   X64ASM:RAX DATA-REG QSORT-FN X64ASM:MEM-OFF X64CODE:ASM-SINK X64ASM:ENC-MOV-MR
   ARGS X64HARNESS:PUSH-DATA,  4 N,
   X64ASM:RAX DATA-REG QSORT-FN X64ASM:MEM-OFF X64CODE:ASM-SINK X64ASM:ENC-MOV-RM  0 X64RT:G-PUSH
   s" ffi-call" ROW  0 X64RT:G-POP
   1 VALUES X64HARNESS:EXPECT-CELL,
   2 VALUES CELL + X64HARNESS:EXPECT-CELL,
   3 VALUES 2 CELL * + X64HARNESS:EXPECT-CELL,
   1 INNER-VALUES X64HARNESS:EXPECT-CELL,
   2 INNER-VALUES CELL + X64HARNESS:EXPECT-CELL,
   0 CB-XDS X64HARNESS:EXPECT-CELL,
   0 CB-OWNER X64HARNESS:EXPECT-CELL,
   ;

: CALL-ENTRY, ( -- )
   EXIT-STATUS:CALLBACK X64HARNESS:EXPECT-EXIT
   STUB,  X64ASM:RAX X64CODE:ASM-SINK X64ASM:ENC-CALL-REG ;

: UNBOUND-CASE ( -- )
   ROWS CB-ROWS X64HARNESS:DATA-ADDR!,
   CALL-ENTRY, ;

: NO-FRAME-CASE ( -- )
   ROWS CB-ROWS X64HARNESS:DATA-ADDR!,
   0 ROWS X64HARNESS:DATA-ADDR!,
   CALL-ENTRY, ;

: BUILD ( [ -- ] str -- ) {: path:str :}
   false X64HARNESS:BOOT-OPEN,
   execute
   0 X64HARNESS:EXPECT-DEPTH,
   X64HARNESS:EXPECT-BALANCED,
   path X64HARNESS:BOOT-CLOSE, ;

public

: RUN ( -- )
   T-RESET X64HARNESS:INIT
   [: SORT-CASE ;] s" hb-x64-kernel-callback" TMP-PATH BUILD
   [: UNBOUND-CASE ;] s" hb-x64-kernel-callback-unbound" TMP-PATH BUILD
   [: NO-FRAME-CASE ;] s" hb-x64-kernel-callback-no-frame" TMP-PATH BUILD
   X64HARNESS:DISPOSE T-REPORT ;

;package

X64K-CB:RUN
