   s" IR:PACK-SOURCE" ABSENT? TTRUE
   s" IR:SOURCE-LOCAL" ABSENT? TTRUE
   s" IR-ID:MINT-MODULE" ABSENT? TTRUE
   s" IR-ID:MODULE>N" ABSENT? TTRUE
   s" IR-RAW:MINT-MODULE" ABSENT? TTRUE
   s" IR-RAW:SOURCE>N" ABSENT? TTRUE
   s" HIR:MINT-SOURCE" ABSENT? TTRUE
   s" SIR:MINT-SOURCE" ABSENT? TTRUE
   s" LIR:MINT-SOURCE" ABSENT? TTRUE
   s" GPU-IR:MINT-SOURCE" ABSENT? TTRUE ;

public

