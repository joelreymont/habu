package C6XSIM-TEST
private

64 constant PROGRAM-MAX
create PROGRAM PROGRAM-MAX cells allot
variable PROGRAM-LEN

: P-RESET ( -- ) 0 PROGRAM-LEN ! C6XSIM:RESET ;
: P+ ( C6XASM:instruction -- )
   PROGRAM-LEN @ PROGRAM-MAX >= if C6XASM:E-OPERAND throw then
   C6XASM:INSTRUCTION>N PROGRAM PROGRAM-LEN @ cells + ! 1 PROGRAM-LEN +! ;
: P-RETURN ( -- ) 3 C6XASM:B-REG C6XASM:ENC-B-REG P+ 5 C6XASM:ENC-NOP P+ ;
: P-RUN ( -- n ) PROGRAM PROGRAM-LEN @ C6XSIM:CALL ;
: OFFSET ( n n -- C6XASM:branch-offset ) {: from:n target:n :}
   target 4 * from 4 * $FFFFFFE0 and - C6XASM:>BRANCH-OFFSET ;


: MOVE-CASES ( -- )
   P-RESET
   4 C6XASM:A-REG -5 C6XASM:ENC-MVK P+
   5 C6XASM:A-REG $1234 C6XASM:ENC-MVKL P+ 5 C6XASM:A-REG $ABCD1234 C6XASM:ENC-MVKH P+
   6 C6XASM:B-REG $8000 C6XASM:ENC-MVKL P+ 6 C6XASM:B-REG 0 C6XASM:ENC-MVKLH P+
   P-RETURN P-RUN 11 T=
   4 C6XSIM:A@ $FFFFFFFB T= 5 C6XSIM:A@ $ABCD1234 T= 6 C6XSIM:B@ $8000 T= ;


: ARITHMETIC-CASES ( -- )
   P-RESET 7 1 C6XSIM:A! 3 2 C6XSIM:B! $80000000 3 C6XSIM:A! -1 4 C6XSIM:B!
   5 C6XASM:A-REG 1 C6XASM:A-REG 2 C6XASM:B-REG C6XASM:ENC-ADD-L P+
   6 C6XASM:A-REG 1 C6XASM:A-REG 2 C6XASM:B-REG C6XASM:ENC-SUB-L P+
   7 C6XASM:A-REG 1 C6XASM:A-REG -8 C6XASM:ENC-ADD-I5 P+
   8 C6XASM:A-REG 1 C6XASM:A-REG 2 C6XASM:B-REG C6XASM:ENC-AND-L P+ 9 C6XASM:A-REG 1 C6XASM:A-REG 2 C6XASM:B-REG C6XASM:ENC-XOR-L P+
   10 C6XASM:A-REG 3 C6XASM:A-REG C6XASM:ALWAYS C6XASM:ENC-ABS-L P+                       \ ABS saturates INT_MIN to INT_MAX (SPRUGH7)
   11 C6XASM:A-REG 4 C6XASM:B-REG C6XASM:ALWAYS C6XASM:ENC-NORM-L P+                      \ -1 has 31 redundant sign bits
   12 C6XASM:A-REG 1 C6XASM:A-REG C6XASM:ALWAYS C6XASM:ENC-NORM-L P+                      \ 7 has 28
   13 C6XASM:A-REG 3 C6XASM:A-REG C6XASM:ALWAYS C6XASM:ENC-NORM-L P+                      \ INT_MIN has none
   14 C6XASM:A-REG 1 C6XASM:A-REG 2 C6XASM:B-REG C6XASM:ENC-CMPEQ-L P+
   0 C6XASM:A-REG 3 C6XASM:A-REG 1 C6XASM:A-REG C6XASM:ALWAYS C6XASM:ENC-CMPGT-L P+
   1 C6XASM:B-REG 4 C6XASM:B-REG 1 C6XASM:A-REG C6XASM:ALWAYS C6XASM:ENC-CMPGTU-L P+
   2 C6XASM:B-REG 2 C6XASM:B-REG 1 C6XASM:A-REG C6XASM:ALWAYS C6XASM:ENC-CMPLT-L P+
   0 C6XASM:B-REG 4 C6XASM:B-REG 1 C6XASM:A-REG C6XASM:ALWAYS C6XASM:ENC-CMPLTU-L P+
   15 C6XASM:A-REG 1 C6XASM:A-REG -3 C6XASM:ALWAYS C6XASM:ENC-CMPGT-I5 P+
   16 C6XASM:A-REG 1 C6XASM:A-REG 9 C6XASM:ALWAYS C6XASM:ENC-CMPGTU-U4 P+
   17 C6XASM:A-REG 1 C6XASM:A-REG -3 C6XASM:ALWAYS C6XASM:ENC-CMPLT-I5 P+
   18 C6XASM:A-REG 1 C6XASM:A-REG 9 C6XASM:ALWAYS C6XASM:ENC-CMPLTU-U4 P+
   P-RETURN P-RUN drop
   5 C6XSIM:A@ 10 T= 6 C6XSIM:A@ 4 T= 7 C6XSIM:A@ $FFFFFFFF T= 8 C6XSIM:A@ 3 T= 9 C6XSIM:A@ 4 T=
   10 C6XSIM:A@ $7FFFFFFF T= 11 C6XSIM:A@ 31 T= 12 C6XSIM:A@ 28 T= 13 C6XSIM:A@ 0 T= 14 C6XSIM:A@ 0 T=
   0 C6XSIM:A@ 0 T= 1 C6XSIM:B@ 1 T= 2 C6XSIM:B@ 1 T= 0 C6XSIM:B@ 0 T= 15 C6XSIM:A@ 0 T= 16 C6XSIM:A@ 1 T= 17 C6XSIM:A@ 1 T= 18 C6XSIM:A@ 0 T= ;


: SUBC-CASES ( -- )
   P-RESET $125A 1 C6XSIM:A! $1F12 2 C6XSIM:A! 5 3 C6XSIM:A! 3 4 C6XSIM:B! $FFFFFFFF 5 C6XSIM:A! 1 6 C6XSIM:A!
   1 C6XASM:A-REG 1 C6XASM:A-REG 2 C6XASM:A-REG C6XASM:ALWAYS C6XASM:ENC-SUBC-L P+               \ the reference example: 0x125A < 0x1F12
   3 C6XASM:A-REG 3 C6XASM:A-REG 4 C6XASM:B-REG C6XASM:ALWAYS C6XASM:ENC-SUBC-L P+               \ 5 - 3 >= 0: (2 << 1) + 1
   5 C6XASM:A-REG 5 C6XASM:A-REG 6 C6XASM:A-REG C6XASM:ALWAYS C6XASM:ENC-SUBC-L P+               \ the comparison is unsigned
   P-RETURN P-RUN drop
   1 C6XSIM:A@ $24B4 T= 3 C6XSIM:A@ 5 T= 5 C6XSIM:A@ $FFFFFFFD T= ;


: SHIFT-CASES ( -- )
   P-RESET $80000001 1 C6XSIM:A! 4 2 C6XSIM:A! 33 3 C6XSIM:A! -8 4 C6XSIM:B!
   5 C6XASM:A-REG 1 C6XASM:A-REG 2 C6XASM:A-REG C6XASM:ALWAYS C6XASM:ENC-SHL-S P+
   6 C6XASM:A-REG 1 C6XASM:A-REG 2 C6XASM:A-REG C6XASM:ALWAYS C6XASM:ENC-SHR-S P+
   7 C6XASM:A-REG 1 C6XASM:A-REG 2 C6XASM:A-REG C6XASM:ALWAYS C6XASM:ENC-SHRU-S P+
   8 C6XASM:A-REG 1 C6XASM:A-REG 3 C6XASM:A-REG C6XASM:ALWAYS C6XASM:ENC-SHL-S P+                \ counts past 31 clear
   9 C6XASM:A-REG 1 C6XASM:A-REG 3 C6XASM:A-REG C6XASM:ALWAYS C6XASM:ENC-SHR-S P+                \ and fill with the sign
   10 C6XASM:A-REG 4 C6XASM:B-REG 1 C6XASM:ALWAYS C6XASM:ENC-SHR-U5 P+
   11 C6XASM:A-REG 4 C6XASM:B-REG 1 C6XASM:ALWAYS C6XASM:ENC-SHRU-U5 P+
   12 C6XASM:A-REG 1 C6XASM:A-REG 31 C6XASM:ALWAYS C6XASM:ENC-SHL-U5 P+
   P-RETURN P-RUN drop
   5 C6XSIM:A@ $10 T= 6 C6XSIM:A@ $F8000000 T= 7 C6XSIM:A@ $08000000 T= 8 C6XSIM:A@ 0 T= 9 C6XSIM:A@ $FFFFFFFF T=
   10 C6XSIM:A@ $FFFFFFFC T= 11 C6XSIM:A@ $7FFFFFFC T= 12 C6XSIM:A@ $80000000 T= ;


: FIELD-CASES ( -- )
   P-RESET $07A4E01F 1 C6XSIM:A! $A5A5A5A5 2 C6XSIM:A!
   3 C6XASM:A-REG 1 C6XASM:A-REG 12 23 C6XASM:ALWAYS C6XASM:ENC-EXTU-S P+                 \ bits 19..11: 0x9C
   4 C6XASM:A-REG 1 C6XASM:A-REG 12 23 C6XASM:ALWAYS C6XASM:ENC-EXT-S P+
   5 C6XASM:A-REG 2 C6XASM:A-REG 15 23 C6XASM:ALWAYS C6XASM:ENC-SET-S P+                  \ bits 15..23 become ones
   6 C6XASM:A-REG 2 C6XASM:A-REG 15 23 C6XASM:ALWAYS C6XASM:ENC-CLR-S P+
   7 C6XASM:A-REG 1 C6XASM:A-REG 0 31 C6XASM:ALWAYS C6XASM:ENC-EXT-S P+                   \ sign of bit 31
   P-RETURN P-RUN drop
   3 C6XSIM:A@ $9C T= 4 C6XSIM:A@ $9C T= 5 C6XSIM:A@ $A5FFA5A5 T= 6 C6XSIM:A@ $A50025A5 T=
   7 C6XSIM:A@ 0 T= ;


: MEMORY-CASES ( -- )
   P-RESET C6XSIM:MEMORY-BASE 1 C6XSIM:A! $7F 3 C6XSIM:A! $80 4 C6XSIM:A! $11223344 10 C6XSIM:A! $55667788 11 C6XSIM:A!
   3 C6XASM:A-REG 1 C6XASM:A-REG 0 C6XASM:>BYTE-OFFSET C6XASM:ALWAYS C6XASM:ENC-STB P+
   4 C6XASM:A-REG 1 C6XASM:A-REG 1 C6XASM:>BYTE-OFFSET C6XASM:ALWAYS C6XASM:ENC-STB P+
   5 C6XASM:A-REG 1 C6XASM:A-REG 1 C6XASM:>BYTE-OFFSET C6XASM:ALWAYS C6XASM:ENC-LDB P+
   6 C6XASM:A-REG 1 C6XASM:A-REG 1 C6XASM:>BYTE-OFFSET C6XASM:ALWAYS C6XASM:ENC-LDBU P+
   7 C6XASM:A-REG 5 C6XASM:A-REG C6XASM:ENC-MV-L P+                                \ still the old value in the delay slots
   4 C6XASM:ENC-NOP P+
   8 C6XASM:A-REG 5 C6XASM:A-REG C6XASM:ENC-MV-L P+                                \ the loaded value has landed
   10 C6XASM:A-REG 1 C6XASM:A-REG 8 C6XASM:>BYTE-OFFSET C6XASM:ALWAYS C6XASM:ENC-STDW P+
   12 C6XASM:A-REG 1 C6XASM:A-REG 8 C6XASM:>BYTE-OFFSET C6XASM:ALWAYS C6XASM:ENC-LDDW P+
   4 C6XASM:ENC-NOP P+
   9 C6XASM:A-REG 1 C6XASM:A-REG 1 C6XASM:>BYTE-OFFSET C6XASM:ALWAYS C6XASM:ENC-LDB++ P+         \ loads *base, then base moves on
   4 C6XASM:ENC-NOP P+
   14 C6XASM:A-REG 1 C6XASM:A-REG 3 C6XASM:ALWAYS C6XASM:ENC-ADDAW-U5 P+
   15 C6XASM:A-REG 1 C6XASM:A-REG 5 C6XASM:ALWAYS C6XASM:ENC-ADDAB-U5 P+
   P-RETURN P-RUN drop
   C6XSIM:MEMORY-BASE C6XSIM:MEMORY@ $7F T= C6XSIM:MEMORY-BASE 1+ C6XSIM:MEMORY@ $80 T=
   5 C6XSIM:A@ $FFFFFF80 T= 6 C6XSIM:A@ $80 T= 7 C6XSIM:A@ 0 T= 8 C6XSIM:A@ $FFFFFF80 T=
   C6XSIM:MEMORY-BASE 8 + C6XSIM:MEMORY-WORD@ $11223344 T= C6XSIM:MEMORY-BASE 12 + C6XSIM:MEMORY-WORD@ $55667788 T=
   12 C6XSIM:A@ $11223344 T= 13 C6XSIM:A@ $55667788 T=
   9 C6XSIM:A@ $7F T= 1 C6XSIM:A@ C6XSIM:MEMORY-BASE 1+ T= 14 C6XSIM:A@ C6XSIM:MEMORY-BASE 13 + T= 15 C6XSIM:A@ C6XSIM:MEMORY-BASE 6 + T= ;


: BRANCH-CASES ( -- )
   P-RESET
   4 C6XASM:A-REG 1 C6XASM:ENC-MVK P+
   0 C6XASM:>SIDE 1 8 OFFSET C6XASM:ENC-B-REL P+
   5 C6XASM:A-REG 2 C6XASM:ENC-MVK P+ 6 C6XASM:A-REG 3 C6XASM:ENC-MVK P+ 7 C6XASM:A-REG 4 C6XASM:ENC-MVK P+   \ five delay slots execute
   8 C6XASM:A-REG 5 C6XASM:ENC-MVK P+ 9 C6XASM:A-REG 6 C6XASM:ENC-MVK P+
   10 C6XASM:A-REG 7 C6XASM:ENC-MVK P+                                       \ skipped
   11 C6XASM:A-REG 8 C6XASM:ENC-MVK P+                                       \ the target
   P-RETURN P-RUN 14 T=
   4 C6XSIM:A@ 1 T= 9 C6XSIM:A@ 6 T= 10 C6XSIM:A@ 0 T= 11 C6XSIM:A@ 8 T=
   P-RESET
   0 C6XASM:>SIDE 0 3 OFFSET C6XASM:ENC-B-REL 0 C6XASM:A-REG C6XASM:WHEN-NONZERO P+        \ A0 is zero: not taken
   10 C6XASM:A-REG 7 C6XASM:ENC-MVK P+ 5 C6XASM:ENC-NOP P+
   P-RETURN P-RUN drop
   10 C6XSIM:A@ 7 T=
   P-RESET
   1 C6XASM:A-REG 3 C6XASM:ENC-MVK P+ 2 C6XASM:A-REG 0 C6XASM:ENC-MVK P+
   2 C6XASM:A-REG 2 C6XASM:A-REG 5 C6XASM:ENC-ADD-I5 P+                             \ the loop body at word 2
   1 C6XASM:A-REG 1 C6XASM:A-REG -1 C6XASM:ENC-ADD-I5 P+
   0 C6XASM:>SIDE 4 2 OFFSET C6XASM:ENC-B-REL 1 C6XASM:A-REG C6XASM:WHEN-NONZERO P+
   5 C6XASM:ENC-NOP P+
   P-RETURN P-RUN drop
   2 C6XSIM:A@ 15 T= 1 C6XSIM:A@ 0 T= ;


: PREDICATE-CASES ( -- )
   P-RESET -5 1 C6XSIM:A! 0 0 C6XSIM:A! 1 1 C6XSIM:B!
   5 C6XASM:A-REG 1 C6XASM:A-REG 0 C6XASM:A-REG C6XASM:IF-NONZERO C6XASM:ENC-ABS-L P+             \ A0 is zero: skipped
   6 C6XASM:A-REG 1 C6XASM:A-REG 0 C6XASM:A-REG C6XASM:IF-ZERO C6XASM:ENC-ABS-L P+
   7 C6XASM:A-REG 1 C6XASM:A-REG 1 C6XASM:B-REG C6XASM:IF-NONZERO C6XASM:ENC-ABS-L P+
   8 C6XASM:A-REG 1 C6XASM:A-REG 1 C6XASM:B-REG C6XASM:IF-ZERO C6XASM:ENC-ABS-L P+
   P-RETURN P-RUN drop
   5 C6XSIM:A@ 0 T= 6 C6XSIM:A@ 5 T= 7 C6XSIM:A@ 5 T= 8 C6XSIM:A@ 0 T= ;


\ Execute packets: every instruction reads before any writes, one cycle each.
: PACKET-CASES ( -- )
   P-RESET 7 1 C6XSIM:A! 3 2 C6XSIM:B! 9 5 C6XSIM:A!
   5 C6XASM:A-REG 1 C6XASM:A-REG 2 C6XASM:B-REG C6XASM:ENC-ADD-L C6XASM:PARALLEL-NEXT P+           \ .L1: A5 = 7 + 3 ...
   6 C6XASM:A-REG 5 C6XASM:A-REG 0 C6XASM:ALWAYS C6XASM:ENC-SHL-U5 C6XASM:PARALLEL-NEXT P+         \ .S1: ... while A6 takes the old A5
   7 C6XASM:B-REG 2 C6XASM:B-REG 1 C6XASM:ENC-ADD-I5 P+                              \ .L2: three in one cycle
   P-RETURN P-RUN 7 T=
   5 C6XSIM:A@ 10 T= 6 C6XSIM:A@ 9 T= 7 C6XSIM:B@ 4 T=
   P-RESET 1 1 C6XSIM:A! 2 2 C6XSIM:B!
   6 C6XASM:A-REG 1 C6XASM:A-REG 2 C6XASM:B-REG C6XASM:ENC-ADD-L C6XASM:PARALLEL-NEXT P+           \ B2 through 1X ...
   7 C6XASM:A-REG 2 C6XASM:B-REG 1 C6XASM:A-REG C6XASM:ALWAYS C6XASM:ENC-SHL-S P+                  \ ... twice is allowed
   P-RETURN P-RUN drop
   6 C6XSIM:A@ 3 T= 7 C6XSIM:A@ 4 T=
   P-RESET 1 1 C6XSIM:A! 2 C6XASM:ENC-NOP C6XASM:PARALLEL-NEXT P+ 2 C6XASM:A-REG 1 C6XASM:A-REG 3 C6XASM:ENC-ADD-I5 P+   \ the packet, then one idle cycle
   3 C6XASM:A-REG 2 C6XASM:A-REG 0 C6XASM:ALWAYS C6XASM:ENC-SHL-U5 P+                       \ sees the sum
   P-RETURN P-RUN 9 T=
   3 C6XSIM:A@ 4 T= ;


\ Reading through a cross path a register a non-load wrote last cycle costs a cycle.
: STALL-CASES ( -- )
   P-RESET 1 0 C6XSIM:A! 2 0 C6XSIM:B!
   1 C6XASM:A-REG 0 C6XASM:A-REG 0 C6XASM:A-REG C6XASM:ENC-ADD-L P+
   1 C6XASM:B-REG 0 C6XASM:B-REG 1 C6XASM:A-REG C6XASM:ENC-ADD-L P+                         \ .L2 reads A1 through 2X: a stall
   P-RETURN P-RUN 9 T=
   1 C6XSIM:B@ 4 T=
   P-RESET 1 0 C6XSIM:A! 2 0 C6XSIM:B!
   1 C6XASM:A-REG 0 C6XASM:A-REG 0 C6XASM:A-REG C6XASM:ENC-ADD-L P+
   1 C6XASM:ENC-NOP P+
   1 C6XASM:B-REG 0 C6XASM:B-REG 1 C6XASM:A-REG C6XASM:ENC-ADD-L P+                         \ a cycle later: no stall
   P-RETURN P-RUN 9 T=
   P-RESET C6XSIM:MEMORY-BASE 4 C6XSIM:A! 5 C6XSIM:MEMORY-BASE C6XSIM:MEMORY-WORD! 2 0 C6XSIM:B!
   1 C6XASM:A-REG 4 C6XASM:A-REG 0 C6XASM:>BYTE-OFFSET C6XASM:ENC-LDW P+
   4 C6XASM:ENC-NOP P+
   1 C6XASM:B-REG 0 C6XASM:B-REG 1 C6XASM:A-REG C6XASM:ENC-ADD-L P+                         \ a load's value: no stall
   P-RETURN P-RUN 12 T=
   1 C6XSIM:B@ 7 T= ;


\ A load may land beside another write of a different cycle, never the same one.
: LANDING-CASES ( -- )
   P-RESET C6XSIM:MEMORY-BASE 4 C6XSIM:A! 5 C6XSIM:MEMORY-BASE C6XSIM:MEMORY-WORD!
   1 C6XASM:A-REG 4 C6XASM:A-REG 0 C6XASM:>BYTE-OFFSET C6XASM:ENC-LDW P+
   2 C6XASM:ENC-NOP P+
   1 C6XASM:A-REG 9 C6XASM:ENC-MVK P+                                         \ written a cycle before the load lands
   P-RETURN P-RUN drop
   1 C6XSIM:A@ 5 T=
   P-RESET C6XSIM:MEMORY-BASE 4 C6XSIM:A! 5 C6XSIM:MEMORY-BASE C6XSIM:MEMORY-WORD!
   1 C6XASM:A-REG 4 C6XASM:A-REG 0 C6XASM:>BYTE-OFFSET C6XASM:ENC-LDW P+
   4 C6XASM:ENC-NOP P+
   1 C6XASM:A-REG 9 C6XASM:ENC-MVK P+                                         \ written after the load landed
   P-RETURN P-RUN drop
   1 C6XSIM:A@ 9 T= ;


\ A branch landing cuts a multicycle NOP short.
: SHORT-NOP-CASES ( -- )
   P-RESET
   0 C6XASM:>SIDE 0 2 OFFSET C6XASM:ENC-B-REL P+
   9 C6XASM:ENC-NOP P+
   4 C6XASM:A-REG 1 C6XASM:ENC-MVK P+
   P-RETURN P-RUN 13 T=
   4 C6XSIM:A@ 1 T= ;


: UNDECODABLE ( -- ) P-RESET $FFFFFFFF C6XASM:>INSTRUCTION P+ P-RETURN P-RUN drop ;
: SAME-UNIT ( -- )
   P-RESET 5 C6XASM:A-REG 1 C6XASM:A-REG 2 C6XASM:A-REG C6XASM:ENC-ADD-L C6XASM:PARALLEL-NEXT P+ 6 C6XASM:A-REG 1 C6XASM:A-REG 2 C6XASM:A-REG C6XASM:ENC-SUB-L P+
   P-RETURN P-RUN drop ;
: TWO-CROSSED ( -- )
   P-RESET 5 C6XASM:A-REG 1 C6XASM:A-REG 2 C6XASM:B-REG C6XASM:ENC-ADD-L C6XASM:PARALLEL-NEXT P+
   6 C6XASM:A-REG 3 C6XASM:B-REG 1 C6XASM:A-REG C6XASM:ALWAYS C6XASM:ENC-SHL-S P+                  \ a second register on 1X
   P-RETURN P-RUN drop ;
: SAME-DATA-SIDE ( -- )
   P-RESET C6XSIM:MEMORY-BASE 4 C6XSIM:B! C6XSIM:MEMORY-BASE 5 C6XSIM:A!
   7 C6XASM:A-REG 4 C6XASM:B-REG 0 C6XASM:>BYTE-OFFSET C6XASM:ALWAYS C6XASM:ENC-LDB C6XASM:PARALLEL-NEXT P+
   8 C6XASM:A-REG 5 C6XASM:A-REG 0 C6XASM:>BYTE-OFFSET C6XASM:ALWAYS C6XASM:ENC-LDB P+             \ both move data on side A
   P-RETURN P-RUN drop ;
: TWO-IDLES ( -- ) P-RESET 2 C6XASM:ENC-NOP C6XASM:PARALLEL-NEXT P+ 3 C6XASM:ENC-NOP P+ P-RETURN P-RUN drop ;
: TWO-WRITES ( -- )
   P-RESET 1 C6XASM:A-REG 0 C6XASM:A-REG 0 C6XASM:A-REG C6XASM:ENC-ADD-L C6XASM:PARALLEL-NEXT P+ 1 C6XASM:A-REG 0 C6XASM:A-REG 1 C6XASM:ALWAYS C6XASM:ENC-SHL-U5 P+
   P-RETURN P-RUN drop ;
: LATE-WRITE ( -- )
   P-RESET C6XSIM:MEMORY-BASE 4 C6XSIM:A!
   1 C6XASM:A-REG 4 C6XASM:A-REG 0 C6XASM:>BYTE-OFFSET C6XASM:ENC-LDW P+
   3 C6XASM:ENC-NOP P+
   1 C6XASM:A-REG 9 C6XASM:ENC-MVK P+                                         \ lands with the load
   P-RETURN P-RUN drop ;
: TWO-BRANCHES ( -- )
   P-RESET 0 C6XASM:>SIDE 0 2 OFFSET C6XASM:ENC-B-REL C6XASM:PARALLEL-NEXT P+ 1 C6XASM:>SIDE 0 2 OFFSET C6XASM:ENC-B-REL P+
   4 C6XASM:A-REG 1 C6XASM:ENC-MVK P+ P-RETURN P-RUN drop ;
: NINE-WORDS ( -- )
   P-RESET 8 0 ?do 1 C6XASM:ENC-NOP C6XASM:PARALLEL-NEXT P+ loop 1 C6XASM:ENC-NOP P+ P-RETURN P-RUN drop ;
: OUTSIDE ( -- ) P-RESET 5 C6XASM:A-REG 1 C6XASM:A-REG 0 C6XASM:>BYTE-OFFSET C6XASM:ALWAYS C6XASM:ENC-LDB P+ P-RETURN P-RUN drop ;
: FOREVER ( -- ) P-RESET 0 C6XASM:>SIDE 0 0 OFFSET C6XASM:ENC-B-REL P+ 5 C6XASM:ENC-NOP P+ 1000 C6XSIM:BUDGET! P-RUN drop ;
: EMPTY ( -- ) P-RESET P-RUN drop ;

: REJECTIONS ( -- )
   [: UNDECODABLE ;] C6XSIM:E-DECODE TTHROWSQ
   [: OUTSIDE ;] C6XSIM:E-FAULT TTHROWSQ
   [: FOREVER ;] C6XSIM:E-LIMIT TTHROWSQ
   [: EMPTY ;] C6XSIM:E-OPERAND TTHROWSQ
   [: SAME-UNIT ;] C6XSIM:E-CONFLICT TTHROWSQ
   [: TWO-CROSSED ;] C6XSIM:E-CONFLICT TTHROWSQ
   [: SAME-DATA-SIDE ;] C6XSIM:E-CONFLICT TTHROWSQ
   [: TWO-IDLES ;] C6XSIM:E-CONFLICT TTHROWSQ
   [: TWO-WRITES ;] C6XSIM:E-CONFLICT TTHROWSQ
   [: LATE-WRITE ;] C6XSIM:E-CONFLICT TTHROWSQ
   [: TWO-BRANCHES ;] C6XSIM:E-CONFLICT TTHROWSQ
   [: NINE-WORDS ;] C6XSIM:E-CONFLICT TTHROWSQ ;


: RUN ( -- )
   MOVE-CASES ARITHMETIC-CASES SUBC-CASES SHIFT-CASES FIELD-CASES MEMORY-CASES
   BRANCH-CASES PREDICATE-CASES PACKET-CASES STALL-CASES LANDING-CASES SHORT-NOP-CASES REJECTIONS
   T-REPORT ;

RUN
