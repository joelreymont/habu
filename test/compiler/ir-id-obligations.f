\ ir-id-obligations.f - the Rocq obligation text the parity gate makes Rocq prove.
\
\ The module lives in `package COMPILER-ID-ROCQ`. It writes one Rocq source out
\ of live state: the frozen schema in `package COMPILER-ID-PROOF`, the constants
\ read structurally out of `src/compiler/ir/id.f`, and the theorem names in the
\ committed external-axiom manifest. Nothing in it is transcribed.
\
\ Why the obligations are generated rather than written by hand. A hand-written
\ Rocq companion would be a second copy of the vectors, and two copies drift.
\ Here the Habu side and the Rocq side read the one artifact: Habu runs each row
\ through the public `IR-ID` words, and the very same row is turned into a Rocq
\ obligation about `Habu.Common.Ids`. Delete a row, weaken a row, move a bound,
\ or change a Habu constant and the two sides are asked different questions, so
\ one of them refuses.
\
\ Diagnostic class, not just decision. A rejected row does not merely assert that
\ Rocq says no. It names the predicate that says no - the local domain for an
\ index-range row, the scalar domain for a bound, the owner equality for a
\ foreign owner, the strict bound for an off-by-one - so the Habu error code and
\ the Rocq conjunct that fails are bound to each other row by row.
\
\ Statements, not just names. Asking Rocq what a theorem assumes says nothing
\ about what it says, so every theorem the manifest binds is also written out as
\ `Definition pinned_statement_<k> : <manifest type row> := <theorem name>.` The
\ ascribed type is the manifest's copy of the statement, so a proof file that has
\ been rewritten to state something weaker no longer type-checks at the type the
\ committed manifest asks for, and Rocq refuses the generated file.
\
\ Two places where the two sides are genuinely not the same shape, both stated
\ here rather than smoothed over:
\
\   - Rocq's `owner` is an arithmetic shift and Habu's `OWNER-N` is a logical
\     one. They disagree on negative cells. The frozen discriminator cell is
\     emitted with both readings, the fact that the readings differ, and the
\     fact that both land outside the valid serial domain; two lemmas then
\     confine the disagreement to cells `packed_validb` already rejects, which
\     is the whole domain the projections are ever applied to.
\   - Rocq answers exhaustion with an `Exhausted` value and Habu throws
\     `E-IR-MODULE-EXHAUSTED`. That is a decision-to-diagnostic mapping. The
\     Rocq side pins the guard-before-add and the unchanged cell; the Habu side
\     is pinned structurally, because 2^31-1 serials cannot be spent in a test.
\
\ Consumer: `test/compiler/ir-id-proof.f`.

