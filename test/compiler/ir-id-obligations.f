\ ---- emit buffer -------------------------------------------------------------

: +$ ( ptr u8 n -- ) {: a:ptr u:n :}
   V-U @ u + V-CAP > if E-STR-CAPACITY throw then
   a V-BUF V-U @ + u BYTE-COPY
   V-U @ u + V-U ! ;

: +C ( n -- ) {: c:n :}
   V-U @ 1+ V-CAP > if E-STR-CAPACITY throw then
   c V-BUF V-U @ + c!
   V-U @ 1+ V-U ! ;

: +NL ( -- )
   LF +C ;

\ A negative Rocq numeral needs parentheses wherever it stands as an argument,
\ so every emitted number carries them exactly when it is negative.
: +N ( n -- ) {: v:n :}
   v 0 < if s" (" +$ then
   SB-RESET v FMT:SB-INT SB$ +$
   v 0 < if s" )" +$ then ;

: +RAW ( n n -- ) {: serial:n local:n :}
   s" (Ids.pack " +$ serial +N s"  " +$ local +N s" )" +$ ;

: QED ( -- )
   s" Proof. repeat split; vm_compute; reflexivity. Qed." +$ +NL ;

: ROW-LABEL ( ptr u8 n n n -- ) {: a:ptr u:n idx:n w:n :}
   s" Example " +$ a u +$ s" _" +$ idx +N s" _w" +$ w +N s"  :" +$ +NL ;

