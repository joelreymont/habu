\ ---- witnesses ---------------------------------------------------------------

\ Habu mints its module serials from a process-wide counter the test cannot
\ choose, so each row is asked at both ends of the serial domain instead of at
\ one arbitrary point.
: WITNESS-SERIAL ( n -- n ) {: w:n :}
   w 0= if SERIAL-MIN exit then
   SERIAL-MAX ;

: WITNESS-OTHER ( n -- n ) {: w:n :}
   w 0= if SERIAL-MIN 1+ exit then
   SERIAL-MAX 1- ;

\ ---- pack vectors ------------------------------------------------------------

: PACK-ACCEPT ( n n -- ) {: serial:n local:n :}
   s"   Ids.local_validb " +$ local +N s"  = true" +$ +NL
   s"   /\ pack_decides " +$ serial +N s"  " +$ local +N s"  = true" +$ +NL
   s"   /\ Ids.packed_validb " +$ serial local +RAW s"  = true" +$ +NL
   s"   /\ Ids.owner " +$ serial local +RAW s"  = " +$ serial +N +NL
   s"   /\ Ids.local " +$ serial local +RAW s"  = " +$ local +N s" ." +$ +NL ;

: PACK-REJECT ( n n -- ) {: serial:n local:n :}
   s"   Ids.local_validb " +$ local +N s"  = false" +$ +NL
   s"   /\ pack_decides " +$ serial +N s"  " +$ local +N s"  = false." +$ +NL ;

: PACK-ROW ( n n -- ) {: idx:n w:n :}
   w WITNESS-SERIAL {: serial:n :}
   idx PACK-LOCAL {: local:n :}
   s" pack_row" idx w ROW-LABEL
   idx PACK-CLASS 0= if
      serial local PACK-ACCEPT
   else
      idx PACK-CLASS E-IR-INDEX-RANGE <> if E-CID-ROW throw then
      serial local PACK-REJECT
   then
   QED ;

: EMIT-PACK-AT ( n -- ) {: w:n :}
   PACK-ROWS 0 ?do i w PACK-ROW loop ;

: EMIT-PACK-VECTORS ( -- )
   0 EMIT-PACK-AT
   1 EMIT-PACK-AT ;

\ ---- check vectors -----------------------------------------------------------

: CHECK-ACCEPT ( n n n n -- ) {: expect:n packer:n local:n bound:n :}
   s"   Ids.scalar_validb " +$ bound +N s"  = true" +$ +NL
   s"   /\ Ids.packed_validb " +$ packer local +RAW s"  = true" +$ +NL
   s"   /\ Z.eqb (Ids.owner " +$ packer local +RAW s" ) " +$ expect +N
      s"  = true" +$ +NL
   s"   /\ Z.ltb (Ids.local " +$ packer local +RAW s" ) " +$ bound +N
      s"  = true" +$ +NL
   s"   /\ Ids.checkb " +$ expect +N s"  " +$ bound +N s"  " +$
      packer local +RAW s"  = true." +$ +NL ;

: CHECK-BOUND-REJECT ( n n n n -- ) {: expect:n packer:n local:n bound:n :}
   s"   Ids.scalar_validb " +$ bound +N s"  = true" +$ +NL
   s"   /\ Ids.packed_validb " +$ packer local +RAW s"  = true" +$ +NL
   s"   /\ Z.eqb (Ids.owner " +$ packer local +RAW s" ) " +$ expect +N
      s"  = true" +$ +NL
   s"   /\ Z.ltb (Ids.local " +$ packer local +RAW s" ) " +$ bound +N
      s"  = false" +$ +NL
   s"   /\ Ids.checkb " +$ expect +N s"  " +$ bound +N s"  " +$
      packer local +RAW s"  = false." +$ +NL ;

: CHECK-OWNER-REJECT ( n n n n -- ) {: expect:n packer:n local:n bound:n :}
   s"   Ids.scalar_validb " +$ bound +N s"  = true" +$ +NL
   s"   /\ Ids.packed_validb " +$ packer local +RAW s"  = true" +$ +NL
   s"   /\ Z.eqb (Ids.owner " +$ packer local +RAW s" ) " +$ expect +N
      s"  = false" +$ +NL
   s"   /\ Ids.checkb " +$ expect +N s"  " +$ bound +N s"  " +$
      packer local +RAW s"  = false." +$ +NL ;

: CHECK-SCALAR-REJECT ( n n n n -- ) {: expect:n packer:n local:n bound:n :}
   s"   Ids.scalar_validb " +$ bound +N s"  = false" +$ +NL
   s"   /\ Ids.checkb " +$ expect +N s"  " +$ bound +N s"  " +$
      packer local +RAW s"  = false." +$ +NL ;

: CHECK-BODY ( n n n n n -- ) {: expect:n packer:n local:n bound:n class:n :}
   class 0= if expect packer local bound CHECK-ACCEPT exit then
   class E-IR-INDEX-BOUND = if
      expect packer local bound CHECK-BOUND-REJECT exit
   then
   class E-IR-OWNER = if
      expect packer local bound CHECK-OWNER-REJECT exit
   then
   class E-IR-SCALAR-RANGE <> if E-CID-ROW throw then
   expect packer local bound CHECK-SCALAR-REJECT ;

: CHECK-ROW ( n n -- ) {: idx:n w:n :}
   w WITNESS-SERIAL {: expect:n :}
   idx CHECK-OWNER OWNER-OTHER =
   if w WITNESS-OTHER else w WITNESS-SERIAL then {: packer:n :}
   s" check_row" idx w ROW-LABEL
   expect packer idx CHECK-LOCAL idx CHECK-BOUND idx CHECK-CLASS CHECK-BODY
   QED ;

: EMIT-CHECK-AT ( n -- ) {: w:n :}
   CHECK-ROWS 0 ?do i w CHECK-ROW loop ;

: EMIT-CHECK-VECTORS ( -- )
   0 EMIT-CHECK-AT
   1 EMIT-CHECK-AT ;

\ ---- scalar vectors ----------------------------------------------------------

\ An accepted scalar must come back whole. For a value that carries bits above
\ the local field, the two projections are also asked to differ from it, which
\ is what tells a plain number apart from a packed identity.
: SCALAR-ACCEPT ( n -- ) {: value:n :}
   s"   Ids.scalar_validb " +$ value +N s"  = true" +$ +NL
   s"   /\ count_decides " +$ value +N s"  = true" +$ +NL
   s"   /\ pool_decides " +$ value +N s"  = true" +$ +NL
   s"   /\ Ids.count_raw (Ids.MkCount " +$ value +N s" ) = " +$ value +N +NL
   s"   /\ Ids.pool_offset_raw (Ids.MkPoolOffset " +$ value +N s" ) = " +$
      value +N +NL
   value LOCAL-SHIFT rshift 0 <> if
      s"   /\ Z.eqb (Ids.local " +$ value +N s" ) " +$ value +N s"  = false" +$ +NL
      s"   /\ Z.eqb (Ids.owner " +$ value +N s" ) " +$ value +N s"  = false" +$ +NL
   then
   s"   ." +$ +NL ;

: SCALAR-REJECT ( n -- ) {: value:n :}
   s"   Ids.scalar_validb " +$ value +N s"  = false" +$ +NL
   s"   /\ count_decides " +$ value +N s"  = false" +$ +NL
   s"   /\ pool_decides " +$ value +N s"  = false." +$ +NL ;

: SCALAR-ROW ( n -- ) {: idx:n :}
   s" scalar_row" idx 0 ROW-LABEL
   idx SCALAR-CLASS 0= if
      idx SCALAR-VALUE SCALAR-ACCEPT
   else
      idx SCALAR-CLASS E-IR-SCALAR-RANGE <> if E-CID-ROW throw then
      idx SCALAR-VALUE SCALAR-REJECT
   then
   QED ;

: EMIT-SCALAR-VECTORS ( -- )
   SCALAR-ROWS 0 ?do i SCALAR-ROW loop ;

\ ---- the one place the two projections disagree ------------------------------

: EMIT-SHIFT-LEMMAS ( -- )
   s" Lemma reachable_nonneg :" +$ +NL
   s"   forall raw, Ids.packed_validb raw = true -> 0 <= raw <= Ids.cell_max." +$ +NL
   s" Proof." +$ +NL
   s"   intros raw Hvalid." +$ +NL
   s"   rewrite <- (IdLaws.projection_pack_roundtrip raw Hvalid)." +$ +NL
   s"   unfold Ids.packed_validb in Hvalid." +$ +NL
   s"   apply Bool.andb_true_iff in Hvalid as [Hprefix Hlocal]." +$ +NL
   s"   apply Bool.andb_true_iff in Hprefix as [_ Hserial]." +$ +NL
   s"   apply IdLaws.pack_within_signed_cell; assumption." +$ +NL
   s" Qed." +$ +NL
   s" Lemma reachable_owner_readings_agree :" +$ +NL
   s"   forall raw," +$ +NL
   s"     Ids.packed_validb raw = true -> owner_logical raw = Ids.owner raw." +$ +NL
   s" Proof." +$ +NL
   s"   intros raw Hvalid." +$ +NL
   s"   pose proof (reachable_nonneg raw Hvalid) as [Hlo Hhi]." +$ +NL
   s"   change (raw <= 9223372036854775807) in Hhi." +$ +NL
   s"   unfold owner_logical." +$ +NL
   s"   replace 18446744073709551615 with (Z.ones 64) by reflexivity." +$ +NL
   s"   rewrite Z.land_ones by lia." +$ +NL
   s"   rewrite Z.mod_small by lia." +$ +NL
   s"   reflexivity." +$ +NL
   s" Qed." +$ +NL ;

\ The frozen discriminator cell: bit 63 set, so the arithmetic shift the model
\ uses and the logical shift the engine uses read different owners out of it.
\ Both readings leave the valid serial domain, so both sides reject; the reading
\ that differs is recorded rather than hidden, and the lemmas above show the
\ disagreement cannot occur on a cell the packer can produce.
\ The model shifts arithmetically; the engine shifts logically. On a 64-bit
\ two's-complement cell the two readings differ by exactly one whole local field
\ on a negative cell and not at all on a non-negative one, so the model's reading
\ is derived from the engine's rather than restated.
: ARITH-OWNER ( n -- n ) {: v:n :}
   v LOCAL-SHIFT rshift {: hi:n :}
   v 0 < if hi LOCAL-MASK 1+ - exit then
   hi ;

: EMIT-DISCRIMINATOR ( -- )
   LOCAL-MASK LOCAL-SHIFT lshift 5 or {: cell:n :}
   s" Example discriminator_owner_readings :" +$ +NL
   s"   Ids.packed_validb " +$ cell +N s"  = false" +$ +NL
   s"   /\ Ids.owner " +$ cell +N s"  = " +$ cell ARITH-OWNER +N +NL
   s"   /\ owner_logical " +$ cell +N s"  = " +$ cell LOCAL-SHIFT rshift +N +NL
   s"   /\ Z.eqb (Ids.owner " +$ cell +N s" ) (owner_logical " +$ cell +N
      s" ) = false" +$ +NL
   s"   /\ Ids.serial_validb (Ids.owner " +$ cell +N s" ) = false" +$ +NL
   s"   /\ Ids.serial_validb (owner_logical " +$ cell +N s" ) = false" +$ +NL
   s"   /\ Ids.local_validb " +$ cell +N s"  = false" +$ +NL
   s"   /\ Ids.scalar_validb " +$ cell +N s"  = false." +$ +NL
   QED ;

\ ---- the allocator -----------------------------------------------------------

\ Habu answers exhaustion with a throw and Rocq answers with a value. These are
\ the Rocq half of that mapping: the guard runs before the addition, the cell is
\ left alone, a fresh cell issues, and a stale view retries without moving the
\ cell. The Habu half is the frozen `SERIAL-NEXT`, `TRY-SERIAL` and
\ `TAKE-SERIAL` bodies the gate reads out of the production source.
: EMIT-ALLOCATOR ( -- )
   s" Example allocator_guard_precedes_addition :" +$ +NL
   s"   IdAllocator.next_serial 0 = Some 1" +$ +NL
   s"   /\ IdAllocator.next_serial (Ids.serial_max - 1) = Some Ids.serial_max" +$ +NL
   s"   /\ IdAllocator.next_serial Ids.serial_max = None" +$ +NL
   s"   /\ IdAllocator.next_serial (-1) = None" +$ +NL
   s"   /\ IdAllocator.next_serial (Ids.serial_max + 1) = None." +$ +NL
   QED
   s" Example allocator_exhaustion_keeps_state :" +$ +NL
   s"   IdAllocator.pure_attempt (IdAllocator.Cell 3 Ids.serial_max) Ids.serial_max" +$ +NL
   s"     = (IdAllocator.Cell 3 Ids.serial_max, IdAllocator.Exhausted Ids.serial_max)." +$ +NL
   QED
   s" Example allocator_cas_issues :" +$ +NL
   s"   IdAllocator.cas (IdAllocator.Cell 3 0) 0 1" +$ +NL
   s"     = (IdAllocator.Cell 3 1, IdAllocator.CasOk 0 1)" +$ +NL
   s"   /\ IdAllocator.pure_attempt (IdAllocator.Cell 3 0) 0" +$ +NL
   s"     = (IdAllocator.Cell 3 1, IdAllocator.Issued 1)." +$ +NL
   QED
   s" Example allocator_stale_view_retries :" +$ +NL
   s"   IdAllocator.cas (IdAllocator.Cell 3 1) 0 1" +$ +NL
