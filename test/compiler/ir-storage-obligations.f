$20000 constant V-CAP
$0A constant LF
$22 constant DQ

create V-BUF V-CAP allot

variable V-U
variable PIN-N

\ ---- emit buffer -------------------------------------------------------------

: +$ ( ptr u8 n -- ) {: a:ptr u:n :}
   V-U @ u + V-CAP > if E-STR-CAPACITY throw then
   a V-BUF V-U @ + u BYTE-COPY
   V-U @ u + V-U ! ;

: +C ( n -- ) {: c:n :}
   V-U @ 1+ V-CAP > if E-STR-CAPACITY throw then
   c V-BUF V-U @ + c!
   V-U @ 1+ V-U ! ;

: +NL ( -- )
   LF +C ;

: +N ( n -- )
   SB-RESET FMT:SB-INT SB$ +$ ;

\ ---- preamble ----------------------------------------------------------------
\ The same imports the model itself opens, with the model imported last, so a
\ name the manifest wrote down resolves here exactly as it did where Rocq printed
\ it.

: EMIT-HEAD ( -- )
   s" (* Generated by test/compiler/ir-storage-proof.f from the shared storage" +$ +NL
   s"    vector rows and the committed manifest. A build output: never committed. *)" +$ +NL
   s" From Stdlib Require Import Bool List Lia Arith." +$ +NL
   s" Import ListNotations." +$ +NL
   s" From Habu.Common Require Import Storage." +$ +NL
   s" Set Printing Width 200." +$ +NL ;

\ ---- the pinned capacity constants -------------------------------------------

: EMIT-PIN ( n -- ) {: row:n :}
   s" Example pinned_capacity_" +$ row +N s"  : " +$
   row PIN-MODEL$ +$ s"  = " +$ row PIN-VALUE +N s" ." +$ +NL
   s" Proof. reflexivity. Qed." +$ +NL ;

: EMIT-PINS ( -- )
   PIN-COUNT 0 ?do i EMIT-PIN loop ;

\ ---- the arena machine -------------------------------------------------------
\ Six pieces of state and one owner serial, stepped by the operation codes the
\ shared table uses. A refusal answers `None` and carries the machine forward.

: EMIT-ARENA-MACHINE ( -- )
   s" Record avm : Type := MkAVM {" +$ +NL
   s"   vA : arena; vB : arena; vM0 : amark; vM1 : amark;" +$ +NL
   s"   vX : cell_id; vV : arena; vOwner : nat }." +$ +NL
   s" Definition asel (m : avm) (w : nat) : arena :=" +$ +NL
   s"   if Nat.eqb w 0 then vA m else vB m." +$ +NL
   s" Definition aput (m : avm) (w : nat) (a : arena) : avm :=" +$ +NL
   s"   if Nat.eqb w 0" +$ +NL
   s"   then MkAVM a (vB m) (vM0 m) (vM1 m) (vX m) (vV m) (vOwner m)" +$ +NL
   s"   else MkAVM (vA m) a (vM0 m) (vM1 m) (vX m) (vV m) (vOwner m)." +$ +NL
   s" Definition aputm (m : avm) (slot : nat) (k : amark) : avm :=" +$ +NL
   s"   if Nat.eqb slot 0" +$ +NL
   s"   then MkAVM (vA m) (vB m) k (vM1 m) (vX m) (vV m) (vOwner m)" +$ +NL
   s"   else MkAVM (vA m) (vB m) (vM0 m) k (vX m) (vV m) (vOwner m)." +$ +NL
   s" Definition agetm (m : avm) (slot : nat) : amark :=" +$ +NL
   s"   if Nat.eqb slot 0 then vM0 m else vM1 m." +$ +NL
   s" Definition aputx (m : avm) (x : cell_id) : avm :=" +$ +NL
   s"   MkAVM (vA m) (vB m) (vM0 m) (vM1 m) x (vV m) (vOwner m)." +$ +NL
   s" Definition aputv (m : avm) (v : arena) : avm :=" +$ +NL
   s"   MkAVM (vA m) (vB m) (vM0 m) (vM1 m) (vX m) v (vOwner m)." +$ +NL ;

: EMIT-ARENA-STEP ( -- )
   s" Definition astep (m : avm) (w op arg : nat) : avm * option nat :=" +$ +NL
   s"   let a := asel m w in" +$ +NL
   s"   if Nat.eqb op 0 then" +$ +NL
   s"     match apush (vOwner m) a arg with" +$ +NL
   s"     | Some (a', i) => (aput m w a', Some i)" +$ +NL
   s"     | None => (m, None) end" +$ +NL
   s"   else if Nat.eqb op 1 then" +$ +NL
   s"     if afrozen a then (m, None)" +$ +NL
   s"     else match amint a arg with" +$ +NL
   s"          | Some x => (m, apeek a x)" +$ +NL
   s"          | None => (m, None) end" +$ +NL
   s"   else if Nat.eqb op 2 then" +$ +NL
   s"     (if afrozen a then (m, None) else (m, Some (acount a)))" +$ +NL
   s"   else if Nat.eqb op 3 then" +$ +NL
   s"     match amark_of a with" +$ +NL
   s"     | Some k => (aputm m arg k, Some (mk_cur k))" +$ +NL
   s"     | None => (m, None) end" +$ +NL
   s"   else if Nat.eqb op 4 then" +$ +NL
   s"     match arollback a (agetm m arg) with" +$ +NL
   s"     | Some a' => (aput m w a', Some (acount a'))" +$ +NL
   s"     | None => (m, None) end" +$ +NL
   s"   else if Nat.eqb op 5 then" +$ +NL
   s"     match afreeze a with" +$ +NL
   s"     | Some a' => (aputv (aput m w a') a', Some (acount a'))" +$ +NL
   s"     | None => (m, None) end" +$ +NL
   s"   else if Nat.eqb op 6 then" +$ +NL
   s"     (if afrozen (vV m)" +$ +NL
   s"      then match amint (vV m) arg with" +$ +NL
   s"           | Some x => (m, aat (vV m) x)" +$ +NL
   s"           | None => (m, None) end" +$ +NL
   s"      else (m, None))" +$ +NL
   s"   else if Nat.eqb op 7 then" +$ +NL
   s"     (if afrozen a then (m, None)" +$ +NL
   s"      else match amint a arg with" +$ +NL
   s"           | Some x => (aputx m x, Some (idx_ord x))" +$ +NL
   s"           | None => (m, None) end)" +$ +NL
   s"   else (m, apeek a (vX m))." +$ +NL
   s" Fixpoint arun (m : avm) (steps : list (nat * nat * nat))" +$ +NL
   s"   : list (option nat) :=" +$ +NL
   s"   match steps with" +$ +NL
   s"   | [] => []" +$ +NL
   s"   | (w, op, arg) :: rest =>" +$ +NL
   s"       match astep m w op arg with" +$ +NL
   s"       | (m', ans) => ans :: arun m' rest" +$ +NL
   s"       end" +$ +NL
   s"   end." +$ +NL ;

\ The placeholder arena is the third arena the Habu runner creates: one cell
\ pushed, both marks taken from it, then frozen. Generations 1, 2 and 3 stand for
\ three distinct slots of the one monotone counter.
: EMIT-ARENA-INIT ( -- )
   s" Definition aplaceholder : arena := MkArena 3 1 [0] 1 1 true." +$ +NL
   s" Definition ainit (ceil : nat) : avm :=" +$ +NL
   s"   MkAVM (MkArena 1 1 [] (Nat.min ceil seed_cells) ceil false)" +$ +NL
   s"         (MkArena 2 1 [] (Nat.min ceil seed_cells) ceil false)" +$ +NL
   s"         (MkMark 3 1) (MkMark 3 1) (MkIdx 3 0) aplaceholder 1." +$ +NL ;

\ ---- the context machine -----------------------------------------------------

: EMIT-CTX-MACHINE ( -- )
   s" Record cvm : Type := MkCVM { cOff : nat; cMinted : nat; cCeil : nat }." +$ +NL
   s" Definition cstep (m : cvm) (op arg : nat) : cvm * option nat :=" +$ +NL
   s"   if Nat.eqb op 0 then" +$ +NL
   s"     match scratch_take (cOff m) arg with" +$ +NL
   s"     | Some (_, off') =>" +$ +NL
   s"         (MkCVM off' (cMinted m) (cCeil m), Some (off' - hdr_bytes))" +$ +NL
   s"     | None => (m, None) end" +$ +NL
   s"   else if Nat.eqb op 1 then" +$ +NL
   s"     match mint_take (cMinted m) (cCeil m) with" +$ +NL
   s"     | Some k => (MkCVM (cOff m) k (cCeil m), Some k)" +$ +NL
   s"     | None => (m, None) end" +$ +NL
   s"   else if Nat.eqb op 2 then (m, Some (cOff m - hdr_bytes))" +$ +NL
   s"   else (m, Some (cMinted m))." +$ +NL
   s" Fixpoint crun (m : cvm) (steps : list (nat * nat))" +$ +NL
   s"   : list (option nat) :=" +$ +NL
   s"   match steps with" +$ +NL
   s"   | [] => []" +$ +NL
   s"   | (op, arg) :: rest =>" +$ +NL
   s"       match cstep m op arg with" +$ +NL
   s"       | (m', ans) => ans :: crun m' rest" +$ +NL
   s"       end" +$ +NL
   s"   end." +$ +NL
   s" Definition cinit (ceil : nat) : cvm := MkCVM hdr_bytes 0 ceil." +$ +NL ;

\ ---- one arena row -----------------------------------------------------------

: +ANSWER ( n -- ) {: st:n :}
   st STEP-CLASS@ 0 <> if s" None" +$ exit then
   s" Some " +$ st STEP-ANS@ +N ;

: +STEP ( n -- ) {: st:n :}
   s" (" +$ st STEP-WHICH@ +N s" , " +$ st STEP-OP@ +N s" , " +$
      st STEP-ARG@ +N s" )" +$ ;

: EMIT-ROW ( n -- ) {: s:n :}
   s" Example arena_" +$ s SCN-ROLE@ ROLE-NAME$ +$ s" _" +$ s +N s"  :" +$ +NL
   s"   arun (ainit " +$ s SCN-CEIL@ +N s" ) [" +$
   s SCN-LEN@ 0 ?do
      i 0 > if s" ; " +$ then
      s SCN-BASE@ i + +STEP
   loop
   s" ]" +$ +NL
   s"     = [" +$
   s SCN-LEN@ 0 ?do
      i 0 > if s" ; " +$ then
      s SCN-BASE@ i + +ANSWER
   loop
   s" ]." +$ +NL
   s" Proof. vm_compute. reflexivity. Qed." +$ +NL ;

: EMIT-ROWS ( -- )
   SCENARIOS 0 ?do i EMIT-ROW loop ;

