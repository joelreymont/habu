require src/lib/test/assert.f
require src/arch/arm32/asm.f

package A32ASM-TEST
private

: ARM= ( A32ASM:arm-instruction n -- )
   swap A32ASM:ARM-INSTRUCTION>N swap T= ;

: THUMB16= ( A32ASM:thumb16-instruction n -- )
   swap A32ASM:THUMB16-INSTRUCTION>N swap T= ;

: THUMB32= ( A32ASM:thumb32-instruction n -- )
   swap A32ASM:THUMB32-INSTRUCTION>N swap T= ;

: ARM-DATA-CASES ( -- )
   4 A32ASM:>GPR $ABCD A32ASM:ARM-MOVW $E30A4BCD ARM=
   14 A32ASM:>GPR $FFFF A32ASM:ARM-MOVT $E34FEFFF ARM=
   4 A32ASM:>GPR 5 A32ASM:>GPR 6 A32ASM:>GPR A32ASM:ARM-ADD $E0854006 ARM=
   0 A32ASM:>GPR 14 A32ASM:>GPR A32ASM:ARM-CMP $E150000E ARM= ;

: ARM-CONTROL-CASES ( -- )
   14 A32ASM:>GPR 13 A32ASM:>GPR -4095 A32ASM:ARM-LDR $E51DEFFF ARM=
   14 A32ASM:>GPR A32ASM:ARM-BX $E12FFF1E ARM=
   A32ASM:AL 33554428 A32ASM:>BRANCH-OFFSET A32ASM:ARM-B $EA7FFFFF ARM=
   A32ASM:AL -33554432 A32ASM:>BRANCH-OFFSET A32ASM:ARM-BL $EB800000 ARM= ;

: THUMB-SHORT-CASES ( -- )
   7 A32ASM:>GPR 255 A32ASM:THUMB-MOVS $27FF THUMB16=
   0 A32ASM:>GPR 1 A32ASM:>GPR 7 A32ASM:>GPR A32ASM:THUMB-ADDS $19C8 THUMB16=
   7 A32ASM:>GPR 6 A32ASM:>GPR 124 A32ASM:THUMB-LDR $6FF7 THUMB16=
   14 A32ASM:>GPR A32ASM:THUMB-BX $4770 THUMB16= ;

: THUMB-SHORT-BRANCHES ( -- )
   -2048 A32ASM:>BRANCH-OFFSET A32ASM:THUMB-B-SHORT $E400 THUMB16=
   2046 A32ASM:>BRANCH-OFFSET A32ASM:THUMB-B-SHORT $E3FF THUMB16=
   0 A32ASM:>CONDITION -256 A32ASM:>BRANCH-OFFSET A32ASM:THUMB-B-COND $D080 THUMB16=
   13 A32ASM:>CONDITION 254 A32ASM:>BRANCH-OFFSET A32ASM:THUMB-B-COND $DD7F THUMB16= ;

: THUMB-WIDE-CASES ( -- )
   12 A32ASM:>GPR $ABCD A32ASM:THUMB-MOVW $F64A3CCD THUMB32=
   14 A32ASM:>GPR $FFFF A32ASM:THUMB-MOVT $F6CF7EFF THUMB32=
   14 A32ASM:>GPR 13 A32ASM:>GPR 4095 A32ASM:THUMB-LDR-WIDE $F8DDEFFF THUMB32=
   8 A32ASM:>GPR 12 A32ASM:>GPR 0 A32ASM:THUMB-STR-WIDE $F8CC8000 THUMB32= ;

: THUMB-WIDE-BRANCHES ( -- )
   -16777216 A32ASM:>BRANCH-OFFSET A32ASM:THUMB-B-WIDE $F4009000 THUMB32=
   16777214 A32ASM:>BRANCH-OFFSET A32ASM:THUMB-BL $F3FFD7FF THUMB32=
   -2 A32ASM:>BRANCH-OFFSET A32ASM:THUMB-BL $F7FFFFFF THUMB32=
   0 A32ASM:>BRANCH-OFFSET A32ASM:THUMB-B-WIDE $F000B800 THUMB32= ;

: REGISTER-REJECTIONS ( -- )
   [: -1 A32ASM:>GPR A32ASM:ARM-BX drop ;] A32ASM:E-OPERAND TTHROWSQ
   [: 15 A32ASM:>GPR 0 A32ASM:ARM-MOV-I8 drop ;] A32ASM:E-OPERAND TTHROWSQ
   [: 8 A32ASM:>GPR 0 A32ASM:THUMB-MOVS drop ;] A32ASM:E-OPERAND TTHROWSQ
   [: 13 A32ASM:>GPR 0 A32ASM:THUMB-MOVW drop ;] A32ASM:E-OPERAND TTHROWSQ
   [: 15 A32ASM:>GPR A32ASM:THUMB-BX drop ;] A32ASM:E-OPERAND TTHROWSQ ;

: CONSTANT-REJECTIONS ( -- )
   [: 0 A32ASM:>GPR -1 A32ASM:ARM-MOV-I8 drop ;] A32ASM:E-OPERAND TTHROWSQ
   [: 0 A32ASM:>GPR 256 A32ASM:ARM-MOV-I8 drop ;] A32ASM:E-OPERAND TTHROWSQ
   [: 0 A32ASM:>GPR 65536 A32ASM:ARM-MOVW drop ;] A32ASM:E-OPERAND TTHROWSQ
   [: 0 A32ASM:>GPR -1 A32ASM:THUMB-MOVT drop ;] A32ASM:E-OPERAND TTHROWSQ ;

: MEMORY-REJECTIONS ( -- )
   [: 0 A32ASM:>GPR 1 A32ASM:>GPR -4096 A32ASM:ARM-LDR drop ;] A32ASM:E-OPERAND TTHROWSQ
   [: 0 A32ASM:>GPR 1 A32ASM:>GPR 4096 A32ASM:ARM-STR drop ;] A32ASM:E-OPERAND TTHROWSQ
   [: 0 A32ASM:>GPR 1 A32ASM:>GPR 2 A32ASM:THUMB-LDR drop ;] A32ASM:E-OPERAND TTHROWSQ
   [: 0 A32ASM:>GPR 1 A32ASM:>GPR -4 A32ASM:THUMB-STR drop ;] A32ASM:E-OPERAND TTHROWSQ
   [: 0 A32ASM:>GPR 1 A32ASM:>GPR 4096 A32ASM:THUMB-LDR-WIDE drop ;] A32ASM:E-OPERAND TTHROWSQ ;

: ARM-BRANCH-REJECTIONS ( -- )
   [: A32ASM:AL 2 A32ASM:>BRANCH-OFFSET A32ASM:ARM-B drop ;] A32ASM:E-OPERAND TTHROWSQ
   [: A32ASM:AL 33554432 A32ASM:>BRANCH-OFFSET A32ASM:ARM-B drop ;] A32ASM:E-OPERAND TTHROWSQ
   [: A32ASM:AL -33554436 A32ASM:>BRANCH-OFFSET A32ASM:ARM-BL drop ;] A32ASM:E-OPERAND TTHROWSQ
   [: 15 A32ASM:>CONDITION 0 A32ASM:>BRANCH-OFFSET A32ASM:ARM-B drop ;] A32ASM:E-OPERAND TTHROWSQ ;

: THUMB-BRANCH-REJECTIONS ( -- )
   [: 1 A32ASM:>BRANCH-OFFSET A32ASM:THUMB-B-SHORT drop ;] A32ASM:E-OPERAND TTHROWSQ
   [: 2048 A32ASM:>BRANCH-OFFSET A32ASM:THUMB-B-SHORT drop ;] A32ASM:E-OPERAND TTHROWSQ
   [: 14 A32ASM:>CONDITION 0 A32ASM:>BRANCH-OFFSET A32ASM:THUMB-B-COND drop ;] A32ASM:E-OPERAND TTHROWSQ
   [: 0 A32ASM:>CONDITION 256 A32ASM:>BRANCH-OFFSET A32ASM:THUMB-B-COND drop ;] A32ASM:E-OPERAND TTHROWSQ ;

: THUMB-WIDE-REJECTIONS ( -- )
   [: -3 A32ASM:>BRANCH-OFFSET A32ASM:THUMB-BL drop ;] A32ASM:E-OPERAND TTHROWSQ
   [: -16777218 A32ASM:>BRANCH-OFFSET A32ASM:THUMB-B-WIDE drop ;] A32ASM:E-OPERAND TTHROWSQ
   [: 16777216 A32ASM:>BRANCH-OFFSET A32ASM:THUMB-BL drop ;] A32ASM:E-OPERAND TTHROWSQ ;

: NOMINAL-CASES ( -- )
   s" ARM-GOOD ( A32ASM:gpr -- A32ASM:gpr )" CHECK-QUIET-CANDIDATE! -1 T=
   s" ARM-BAD-REG ( n -- A32ASM:gpr )" CHECK-QUIET-CANDIDATE! 0 T=
   s" ARM-BAD-WIDE ( A32ASM:arm-instruction -- A32ASM:thumb32-instruction )"
      CHECK-QUIET-CANDIDATE! 0 T=
   s" ARM-BAD-SHORT ( A32ASM:thumb16-instruction -- A32ASM:thumb32-instruction )"
      CHECK-QUIET-CANDIDATE! 0 T= ;

: RUN ( -- )
   ARM-DATA-CASES ARM-CONTROL-CASES THUMB-SHORT-CASES THUMB-SHORT-BRANCHES
   THUMB-WIDE-CASES THUMB-WIDE-BRANCHES REGISTER-REJECTIONS CONSTANT-REJECTIONS
   MEMORY-REJECTIONS ARM-BRANCH-REJECTIONS THUMB-BRANCH-REJECTIONS
   THUMB-WIDE-REJECTIONS NOMINAL-CASES T-REPORT ;

RUN
;package
