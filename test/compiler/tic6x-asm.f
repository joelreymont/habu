   [: 3 A-REG 2 A-REG 32 ALWAYS ENC-SHR-U5 drop ;] E-OPERAND TTHROWSQ
   [: 3 A-REG 2 B-REG 4 12 ALWAYS ENC-EXTU-S drop ;] E-OPERAND TTHROWSQ
   [: 3 A-REG 2 A-REG 32 12 ALWAYS ENC-SET-S drop ;] E-OPERAND TTHROWSQ
   [: 5 A-REG 4 A-REG 32 >BYTE-OFFSET ALWAYS ENC-LDB drop ;] E-OPERAND TTHROWSQ
   [: 7 A-REG 4 A-REG 8 >BYTE-OFFSET ALWAYS ENC-LDDW drop ;] E-OPERAND TTHROWSQ
   [: 6 A-REG 4 A-REG 4 >BYTE-OFFSET ALWAYS ENC-STDW++ drop ;] E-OPERAND TTHROWSQ
   [: 6 A-REG 4 B-REG 5 A-REG ALWAYS ENC-ADDAB-D drop ;] E-OPERAND TTHROWSQ
   [: 6 A-REG 4 A-REG 32 ALWAYS ENC-ADDAW-U5 drop ;] E-OPERAND TTHROWSQ ;

