   [: 0 A-REG 2 A-REG 16 ALWAYS ENC-CMPGT-I5 drop ;] E-OPERAND TTHROWSQ
   [: 0 A-REG 2 A-REG 16 ALWAYS ENC-CMPGTU-U4 drop ;] E-OPERAND TTHROWSQ
