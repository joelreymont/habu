5 constant DELTA
1000 constant NEW
2000 constant OTHER

: SUM ( -- n ) VALUE DELTA + ;

: STORE-FETCH, ( -- )
   VALUE X64HARNESS:PUSH,  0 X64HARNESS:PUSH-SCRATCH,
   s" atomic!" X64HARNESS:CALL-ROW,
   VALUE 0 X64HARNESS:EXPECT-SCRATCH,
   0 X64HARNESS:PUSH-SCRATCH,
   s" atomic@" X64HARNESS:CALL-ROW,
   VALUE X64HARNESS:EXPECT-POP,
   s" fence" X64HARNESS:CALL-ROW, ;

: ADD, ( -- )
   DELTA X64HARNESS:PUSH,  0 X64HARNESS:PUSH-SCRATCH,
   s" atomic-add" X64HARNESS:CALL-ROW,
   VALUE X64HARNESS:EXPECT-POP,
   SUM 0 X64HARNESS:EXPECT-SCRATCH, ;

: CAS, ( n n n n -- ) {: expected:n new:n found:n after:n :}
   expected X64HARNESS:PUSH,  new X64HARNESS:PUSH,  0 X64HARNESS:PUSH-SCRATCH,
   s" atomic-cas" X64HARNESS:CALL-ROW,
   found X64HARNESS:EXPECT-POP,
   after 0 X64HARNESS:EXPECT-SCRATCH, ;

\ A value wider than 32 bits, with bit 31 set, over a cell of ones: the store
\ keeps the four bytes beside its word, and the load zero-extends.
$18000004D constant WIDE
$8000004D constant U32
$FFFFFFFF8000004D constant U32-LOW
9 constant HIGH-U32
$98000004D constant U32-BOTH

: U32-AT, ( n n n n -- ) {: v:n off:n cell:n got:n :}
   v X64HARNESS:PUSH,  off X64HARNESS:PUSH-SCRATCH,
   s" atomic-u32!" X64HARNESS:CALL-ROW,
   cell 0 X64HARNESS:EXPECT-SCRATCH,
   off X64HARNESS:PUSH-SCRATCH,
   s" atomic-u32@" X64HARNESS:CALL-ROW,
   got X64HARNESS:EXPECT-POP, ;

: U32-CASE, ( -- )
   -1 X64HARNESS:PUSH,  0 X64HARNESS:PUSH-SCRATCH,
   s" atomic!" X64HARNESS:CALL-ROW,
   WIDE 0 U32-LOW U32 U32-AT,
   HIGH-U32 4 U32-BOTH HIGH-U32 U32-AT,
   0 X64HARNESS:EXPECT-DEPTH,
   X64HARNESS:EXPECT-BALANCED, ;

\ Ten checks, the harness's whole budget.
: ROWS, ( -- )
   STORE-FETCH,  ADD,
   SUM NEW SUM NEW CAS,
   VALUE OTHER NEW NEW CAS,
   0 X64HARNESS:EXPECT-DEPTH,
   X64HARNESS:EXPECT-BALANCED, ;

: BUILD ( bool str -- ) {: negative:bool path:str :}
   negative X64HARNESS:BOOT-OPEN,
   ROWS,
   path X64HARNESS:BOOT-CLOSE, ;

\ ---- the publication rows ----------------------------------------------------
\ RX addresses stay protected while the separate alias accepts engine writes.
\ PROBE, asks clock_gettime to write through RX and must receive -EFAULT.
$1000 constant PAGE
42 constant ANSWER                     \ what the published routine answers
99 constant PATCHED                    \ what it answers once patch32 rewrites it
1 constant IMM-AT                      \ mov eax, imm32: the immediate follows the opcode

: DATA-REG ( -- X64ASM:r64 ) ENGINE-GPR:X64-RBASE X64ASM:>R64 ;
: DBASE-REG ( -- X64ASM:r64 ) ENGINE-GPR:X64-DBASE X64ASM:>R64 ;

: CALL-REGION, ( n -- ) {: off:n :}
   X64ASM:RAX DBASE-REG off X64ASM:MEM-OFF X64CODE:ASM-SINK X64ASM:ENC-LEA
   X64ASM:RAX X64CODE:ASM-SINK X64ASM:ENC-CALL-REG
   0 X64RT:G-PUSH ;

: PUSH-CODE, ( [ -- ] -- n )
   X64CODE:LBL X64CODE:LBL {: code:label past:label :}
   past X64CODE:JMP,
   code X64CODE:LBL,
   X64CODE:ASM-LEN {: start:n :}
   execute
   X64CODE:ASM-LEN start - {: len:n :}
   past X64CODE:LBL,
   X64ASM:RAX code X64CODE:MOVABS,  0 X64RT:G-PUSH
   len ;

\ mov eax, ANSWER; ret: six bytes, a length no instruction-word guard admits.
: ANSWER-CODE, ( -- )
   0 X64ASM:>R32 ANSWER X64ASM:>IMM32 X64CODE:ASM-SINK X64ASM:ENC-MOV32-RI32
   X64CODE:ASM-SINK X64ASM:ENC-RET ;

\ mov eax, ANSWER, eleven nops and ret: 17 bytes, one past a code slot.
: LONG-CODE, ( -- )
   0 X64ASM:>R32 ANSWER X64ASM:>IMM32 X64CODE:ASM-SINK X64ASM:ENC-MOV32-RI32
   11 0 ?do X64CODE:ASM-SINK X64ASM:ENC-NOP loop
   X64CODE:ASM-SINK X64ASM:ENC-RET ;

\ The code slots past DICT-SIZE, and the 17-byte routine's second slot as
\ whole cells: its ret, then the int3 fill.
DICT-SIZE 16 + constant SECOND-SLOT
DICT-SIZE 32 + constant THIRD-SLOT
$CCCCCCCCCCCCCCC3 constant RET-INT3S
$CCCCCCCCCCCCCCCC constant INT3S

: REC ( n n -- n ) {: k:n off:n :} k DREC * off + ;

\ A record's CODE-SPAN length: the cell after its code cell.
X64KERNEL:REC-CODE CELL + constant REC-LEN

\ Store record k's address in PEND-CELL: the pending record does-record reads.
: PEND!, ( n -- ) {: k:n :}
   X64ASM:RAX DBASE-REG k DREC * X64ASM:MEM-OFF X64CODE:ASM-SINK X64ASM:ENC-LEA
   X64ASM:RAX DATA-REG PEND-CELL X64ASM:MEM-OFF X64CODE:ASM-SINK X64ASM:ENC-MOV-MR ;

\ A span from a cell below the control-flow band into it, and a cell two pages
\ past CP.
CFSTK-OFF CELL - constant STRADDLE
DICT-SIZE PAGE 2 * + CELL + constant WIDEN

\ Write through the alias at the record / control-flow boundary, at CP and two
\ pages past CP.
: WINDOW-SETUP, ( -- )
   STRADDLE X64HARNESS:POKE,  CFSTK-OFF X64HARNESS:POKE,
   DICT-SIZE X64HARNESS:POKE,  WIDEN X64HARNESS:POKE, ;

: WINDOW-CASE, ( -- )
   WINDOW-SETUP,
   STRADDLE X64HARNESS:PUSH-REGION-CELL,  -1 X64HARNESS:EXPECT-POP,
   CFSTK-OFF X64HARNESS:PUSH-REGION-CELL,  -1 X64HARNESS:EXPECT-POP,
   DICT-SIZE X64HARNESS:PUSH-REGION-CELL,  -1 X64HARNESS:EXPECT-POP,
   WIDEN X64HARNESS:PUSH-REGION-CELL,  -1 X64HARNESS:EXPECT-POP,
   DICT-SIZE PAGE + X64HARNESS:PROBE-ALIAS,  0 X64HARNESS:EXPECT-POP, ;

\ The RX views reject writes even while the aliases remain writable.
: WINDOW-CLOSED-CASE, ( -- )
   WINDOW-SETUP,
   STRADDLE CELL - X64HARNESS:PROBE,  X64HARNESS:FAULTED X64HARNESS:EXPECT-POP,
   CFSTK-OFF X64HARNESS:PROBE,  X64HARNESS:FAULTED X64HARNESS:EXPECT-POP,
   WIDEN X64HARNESS:PROBE,  X64HARNESS:FAULTED X64HARNESS:EXPECT-POP,
   DICT-SIZE PAGE 3 * + X64HARNESS:PROBE,  X64HARNESS:FAULTED X64HARNESS:EXPECT-POP, ;

: PUBLISH-CASE, ( -- )
   [: ANSWER-CODE, ;] PUSH-CODE, {: len:n :}
   DICT-SIZE X64HARNESS:PUSH-REGION,  len X64HARNESS:PUSH,
   s" code-publish" X64HARNESS:CALL-ROW,
   X64HARNESS:PUSH-CP,  SECOND-SLOT X64HARNESS:EXPECT-POP-REGION,
   DICT-SIZE CALL-REGION,  ANSWER X64HARNESS:EXPECT-POP,
   DICT-SIZE CELL + X64HARNESS:PROBE,  X64HARNESS:FAULTED X64HARNESS:EXPECT-POP,
   PATCHED X64HARNESS:PUSH,  DICT-SIZE IMM-AT + X64HARNESS:PUSH-REGION,
   s" patch32" X64HARNESS:CALL-ROW,
   DICT-SIZE CALL-REGION,  PATCHED X64HARNESS:EXPECT-POP,
   0 X64HARNESS:EXPECT-DEPTH,
   X64HARNESS:EXPECT-BALANCED, ;

\ The fill overwrites the two poisoned cells of the routine's second slot and
\ stops short of the poisoned cell past it, where CP lands.
: PUBLISH-FILL-CASE, ( -- )
   SECOND-SLOT X64HARNESS:POKE,  SECOND-SLOT CELL + X64HARNESS:POKE,  THIRD-SLOT X64HARNESS:POKE,
   [: LONG-CODE, ;] PUSH-CODE, {: len:n :}
   DICT-SIZE X64HARNESS:PUSH-REGION,  len X64HARNESS:PUSH,
   s" code-publish" X64HARNESS:CALL-ROW,
   X64HARNESS:PUSH-CP,  THIRD-SLOT X64HARNESS:EXPECT-POP-REGION,
   SECOND-SLOT X64HARNESS:PUSH-REGION-CELL,  RET-INT3S X64HARNESS:EXPECT-POP,
   SECOND-SLOT CELL + X64HARNESS:PUSH-REGION-CELL,  INT3S X64HARNESS:EXPECT-POP,
   THIRD-SLOT X64HARNESS:PUSH-REGION-CELL,  -1 X64HARNESS:EXPECT-POP,
   0 X64HARNESS:EXPECT-DEPTH,
   X64HARNESS:EXPECT-BALANCED, ;

\ Where the retargets point, and a length that is no whole instruction word.
DICT-SIZE $40 + constant ENTRY-A
DICT-SIZE $80 + constant ENTRY-B
7 constant LEN-A

: RETARGET, ( n n n -- ) {: entry:n len:n idx:n :}
   entry X64HARNESS:PUSH-REGION,  len X64HARNESS:PUSH,  idx X64HARNESS:PUSH,
   s" xref-retarget" X64HARNESS:CALL-ROW, ;

: RETARGET-CASE, ( -- )
   s" alpha" 3 0 X64HARNESS:RECORD,
   s" beta" 3 0 X64HARNESS:RECORD,
   s" gamma" 3 0 X64HARNESS:RECORD,
   ENTRY-A LEN-A 1 RETARGET,
   ENTRY-B CODE-SPAN:MAX 3 RETARGET,             \ record NDICT, the pending one
   0 X64HARNESS:PUSH,  s" rep-mark" X64HARNESS:CALL-ROW,
   1 X64KERNEL:REC-CODE REC X64HARNESS:PUSH-REGION-CELL,  ENTRY-A X64HARNESS:EXPECT-POP-REGION,
   1 REC-LEN REC X64HARNESS:PUSH-REGION-CELL,  LEN-A X64HARNESS:EXPECT-POP,
   3 X64KERNEL:REC-CODE REC X64HARNESS:PUSH-REGION-CELL,  ENTRY-B X64HARNESS:EXPECT-POP-REGION,
   3 REC-LEN REC X64HARNESS:PUSH-REGION-CELL,  CODE-SPAN:MAX X64HARNESS:EXPECT-POP,
   0 X64KERNEL:REC-FLAGS REC X64HARNESS:PUSH-REGION-CELL,
   s" alpha" STR:LEN DNAME-REP or X64HARNESS:EXPECT-POP,
   0 X64KERNEL:REC-FLAGS REC X64HARNESS:PROBE,  X64HARNESS:FAULTED X64HARNESS:EXPECT-POP,
   0 X64HARNESS:EXPECT-DEPTH,
   X64HARNESS:EXPECT-BALANCED, ;

\ A WID-0 record is a global definition. Rewind into its code span and
\ inspect the process-local occurrence slot through the booted kernel.
: RECLAIM-GLOBAL-CASE, ( -- )
   s" global" 0 0 X64HARNESS:RECORD,
   X64ASM:RCX ENGINE-GPR:X64-DBASE X64ASM:>R64 X64CODE:ASM-SINK X64ASM:ENC-MOV-RR
   X64ASM:RCX X64KERNEL:WRITE-ALIAS,
   X64ASM:RAX ENGINE-GPR:X64-DBASE X64ASM:>R64 DICT-SIZE $40 + X64ASM:MEM-OFF X64CODE:ASM-SINK X64ASM:ENC-LEA
   X64ASM:RAX X64ASM:RCX X64KERNEL:REC-CODE X64ASM:MEM-OFF X64CODE:ASM-SINK X64ASM:ENC-MOV-MR
   X64ASM:RAX $20 X64ASM:>IMM32 X64CODE:ASM-SINK X64ASM:ENC-MOV-RI32
   X64ASM:RAX X64ASM:RCX REC-LEN X64ASM:MEM-OFF X64CODE:ASM-SINK X64ASM:ENC-MOV-MR
   X64ASM:RAX DATA-REG DEF-OCC:PTR-CELL X64ASM:MEM-OFF X64CODE:ASM-SINK X64ASM:ENC-MOV-RM
   X64ASM:RCX 1 X64ASM:>IMM32 X64CODE:ASM-SINK X64ASM:ENC-MOV-RI32
   X64ASM:RCX X64ASM:RAX 0 X64ASM:MEM-OFF X64CODE:ASM-SINK X64ASM:ENC-MOV-MR
   X64ASM:RCX X64ASM:RAX CELL X64ASM:MEM-OFF X64CODE:ASM-SINK X64ASM:ENC-MOV-MR
   X64ASM:RAX ENGINE-GPR:X64-DBASE X64ASM:>R64 DICT-SIZE $100 + X64ASM:MEM-OFF X64CODE:ASM-SINK X64ASM:ENC-LEA
   ENGINE-GPR:X64-CP X64ASM:>R64 X64ASM:RAX X64CODE:ASM-SINK X64ASM:ENC-MOV-RR
   DICT-SIZE $50 + X64HARNESS:PUSH-REGION,
   s" cp!" X64HARNESS:CALL-ROW,
   X64ASM:RAX DATA-REG DEF-OCC:PTR-CELL X64ASM:MEM-OFF X64CODE:ASM-SINK X64ASM:ENC-MOV-RM
   X64ASM:RAX X64ASM:RAX CELL X64ASM:MEM-OFF X64CODE:ASM-SINK X64ASM:ENC-MOV-RM
   0 X64RT:G-PUSH  0 X64HARNESS:EXPECT-POP,
   0 X64HARNESS:EXPECT-DEPTH,
   X64HARNESS:EXPECT-BALANCED, ;

\ The two clauses: record 3, past the pending record 2, twice. The short name,
\ 8 bytes, fills a 16-byte code slot at CP; the long name, 22 bytes, lands on
\ the next slot and fills two, and its pad lands in its third and fourth cells.
DICT-SIZE $100 + constant CLAUSE-A
DICT-SIZE $200 + constant CLAUSE-B
9 constant CLAUSE-LEN-A
11 constant CLAUSE-LEN-B
: SHORT$ ( -- str ) s" abc;does" ;
: LONG$ ( -- str ) s" abcdefghijklmnopq;does" ;
DICT-SIZE 16 + constant LONG-AT
LONG-AT CELL 2 * + constant LONG-TAIL
LONG-TAIL CELL + constant LONG-PAD
32 constant LONG-PADDED

: DOES, ( n n -- ) {: entry:n len:n :}
   entry X64HARNESS:PUSH-REGION,  len X64HARNESS:PUSH,
   s" does-record" X64HARNESS:CALL-ROW, ;

: DOES-SETUP, ( -- )
   s" abc" 5 0 X64HARNESS:RECORD,
   s" abcdefghijklmnopq" 6 0 X64HARNESS:RECORD,     \ past DNAME-INL: out of line
   LONG-TAIL X64HARNESS:POKE,  LONG-PAD X64HARNESS:POKE,
   0 PEND!, ;

\ After each clause the clause record's page cannot be written.
: DOES-CLOSED, ( -- )
   3 X64KERNEL:REC-FLAGS REC X64HARNESS:PROBE,  X64HARNESS:FAULTED X64HARNESS:EXPECT-POP, ;

: DOES-CASE, ( -- )
   DOES-SETUP,
   CLAUSE-A CLAUSE-LEN-A DOES,
   DOES-CLOSED,
   3 X64KERNEL:REC-CODE REC X64HARNESS:PUSH-REGION-CELL,  CLAUSE-A X64HARNESS:EXPECT-POP-REGION,
   3 REC-LEN REC X64HARNESS:PUSH-REGION-CELL,  CLAUSE-LEN-A X64HARNESS:EXPECT-POP,
   3 X64KERNEL:REC-FLAGS REC X64HARNESS:PUSH-REGION-CELL,
   SHORT$ STR:LEN DNAME-EXT or X64HARNESS:EXPECT-POP,
   3 X64KERNEL:REC-NAME REC X64HARNESS:PUSH-REGION-CELL,  DICT-SIZE X64HARNESS:EXPECT-POP-REGION,
   DICT-SIZE X64HARNESS:PUSH-REGION-CELL,  SHORT$ 0 X64HARNESS:NAME-CELL X64HARNESS:EXPECT-POP,
   0 X64HARNESS:EXPECT-DEPTH,
   X64HARNESS:EXPECT-BALANCED, ;

\ The long-named parent's clause, published after the short one's, so its name
\ lands at LONG-AT.
: DOES-LONG-CASE, ( -- )
   DOES-SETUP,
   CLAUSE-A CLAUSE-LEN-A DOES,
   1 PEND!,
   CLAUSE-B CLAUSE-LEN-B DOES,
   DOES-CLOSED,
   3 X64KERNEL:REC-FLAGS REC X64HARNESS:PUSH-REGION-CELL,
   LONG$ STR:LEN DNAME-EXT or X64HARNESS:EXPECT-POP,
   3 X64KERNEL:REC-WID REC X64HARNESS:PUSH-REGION-CELL,  6 X64HARNESS:EXPECT-POP,
   LONG-TAIL X64HARNESS:PUSH-REGION-CELL,  s" q;does" 0 X64HARNESS:NAME-CELL X64HARNESS:EXPECT-POP,
   LONG-PAD X64HARNESS:PUSH-REGION-CELL,  0 X64HARNESS:EXPECT-POP,
   X64HARNESS:PUSH-CP,  LONG-AT LONG-PADDED + X64HARNESS:EXPECT-POP-REGION,
   0 X64HARNESS:EXPECT-DEPTH,
   X64HARNESS:EXPECT-BALANCED, ;

: PUBLISH-ARMED, ( n n -- ) {: dst:n len:n :}
   0 X64HARNESS:PUSH,  dst X64HARNESS:PUSH-REGION,  len X64HARNESS:PUSH,
   s" code-publish" X64HARNESS:CALL-ROW, ;

