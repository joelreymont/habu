   X64ASM:RCX DATA-REG INP-CELL X64ASM:MEM-OFF X64CODE:ASM-SINK X64ASM:ENC-MOV-MR
   X64ASM:RDX X64ASM:RCX X64CODE:ASM-SINK X64ASM:ENC-MOV-RR
