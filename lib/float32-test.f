\ float32-test.f - exact scalar F32 conversion tests.

require lib/test.f
require lib/float32.f

package F32-TEST
private

: SPECIALS ( -- )
   1.0 F32:NARROW $3F800000 T=
   1.7 F32:NARROW $3FD9999A T=
   $8000000000000000 IEEE754:BITS>F64 F32:NARROW $80000000 T=
   $3FF0000010000000 IEEE754:BITS>F64 F32:NARROW $3F800000 T=
   $3FF0000030000000 IEEE754:BITS>F64 F32:NARROW $3F800002 T=
   $47F0000000000000 IEEE754:BITS>F64 F32:NARROW $7F800000 T=
   $C7F0000000000000 IEEE754:BITS>F64 F32:NARROW $FF800000 T=
   $7FF8000000000000 IEEE754:BITS>F64 F32:NARROW $7FC00000 T=
   $7FF0000000000001 IEEE754:BITS>F64 F32:NARROW $7FC00000 T=
   $00000001 F32:WIDEN F32:NARROW $00000001 T=
   $007FFFFF F32:WIDEN F32:NARROW $007FFFFF T=
   $80000001 F32:WIDEN F32:NARROW $80000001 T=
   $7FC12345 F32:WIDEN F32:NARROW $7FC12345 T= ;

: NEXT-BITS ( n -- n )
   dup 13 lshift xor
   dup 17 rshift xor
   dup 5 lshift xor
   $FFFFFFFF and ;

: QUIET-EXPECTED ( n -- n ) {: bits:n :}
   bits 23 rshift $FF and $FF =
   bits $7FFFFF and 0= 0= and if bits $400000 or exit then
   bits ;

: PROPERTY-ROWS ( -- )
   $6D2B79F5
   1024 0 ?do
      NEXT-BITS
      dup F32:WIDEN F32:NARROW
      over QUIET-EXPECTED T=
   loop
   drop ;

public

: RUN ( -- )
   T-RESET
   SPECIALS
   PROPERTY-ROWS
   T-REPORT ;

;package

F32-TEST:RUN
