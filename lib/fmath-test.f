: F2-N ( n -- r ) {: exponent:n :}
   exponent 0 < if
      1.0 exponent negate 0 ?do 0.5 f* loop
   else
      1.0 exponent 0 ?do 2.0 f* loop
   then ;

: FNEAR? ( r r r -- bool ) {: got:r want:r tolerance:r :}
   got want f- fabs tolerance f<= ;

: FREL-NEAR? ( r r r -- bool ) {: got:r want:r tolerance:r :}
   got want f- fabs want fabs f/ tolerance f<= ;

: ROOT-PROPERTIES ( n -- ) {: value:n :}
   value FMATH:ISQRT-FLOOR {: floor:n :}
   value FMATH:ISQRT-CEIL {: ceiling:n :}
   value 0= if floor 0 T= ceiling 0 T= exit then
   value floor / floor >= TTRUE
   value floor 1+ / floor 1+ < TTRUE
   ceiling floor = ceiling floor 1+ = or TTRUE
   ceiling floor = if value floor mod 0= TTRUE then ;

