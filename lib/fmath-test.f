\ ---- sine, cosine, pi and power-of-two scaling ----------------------------------
\ References are glibc's binary64 sin/cos (within 1 ulp of correctly rounded),
\ stated as bit patterns so the decimal parser plays no part. FMATH:SIN/COS are
\ within 1 ulp of correctly rounded, so a reference and a result may differ by
\ two units when they round to opposite neighbours.
: ULPS-NEAR? ( r n n -- bool ) {: got:r want:n ulps:n :}
   got IEEE754:F64>BITS want - abs ulps <= ;

: TRIG-AT ( n n n -- ) {: x:n sin:n cos:n :}
   x IEEE754:BITS>F64 FMATH:SIN sin 2 ULPS-NEAR? TTRUE
   x IEEE754:BITS>F64 FMATH:COS cos 2 ULPS-NEAR? TTRUE ;

