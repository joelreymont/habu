   ODIN-ACQ-DONE ODIN-ACQ-WANT ODIN-WAIT-CELL
   ODIN-CSTR5 TASK-CSTRLEN dup TASK-LOCAL-FFI !
   dup 5 <> if ODIN-BAD+ then
   ODIN-FFI-TOTAL atomic-add drop
   TASK-LOCAL-ID @ $63 <> if ODIN-BAD+ then
   100 ODIN-SHARED+
   1 ODIN-DET-DONE atomic-add drop ;

