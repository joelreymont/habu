: TASK-WAIT-READY ( n -- ) {: want:n :}
   begin TASK-READY-CELL atomic@ want < while TASK:PAUSE repeat ;

: TASK-INC-LOCKED ( -- )
   TASK-LOCK TASK:GET
   1 TASK-COUNT atomic-add drop
   TASK-LOCK TASK:RELEASE ;

: TASK-TEST-FACILITY-SWIFT ( -- )
   TASK-LOCK TASK:RELEASE
   TASK-LOCK TASK:GET
   TASK-LOCK TASK:GET
   TASK-LOCK TASK:RELEASE
   TASK-LOCK TASK:RELEASE ;

: TASK-WORK-A ( -- )
   11 TASK-USER-CELL !
   TASK:SELF-N TASK-SELF-A !
   TASK-INC-LOCKED
   1 TASK-READY-CELL atomic-add drop ;

: TASK-WORK-B ( -- )
   22 TASK-USER-CELL !
   TASK:SELF-N TASK-SELF-B !
   TASK-INC-LOCKED
   1 TASK-READY-CELL atomic-add drop ;

: TASK-PAUSER ( -- )
   begin TASK:PAUSE again ;

: TASK-LF ( -- )
   $0A SB-APPEND-C ;

: TASK-DQ ( -- )
   $22 SB-APPEND-C ;

: TASK-LIB-PATH ( -- ptr u8 )
   HB-TARGET-MACOS? if TASK-LIBSYSTEM exit then
   TASK-LIBC ;

: TASK-STRLEN-READY ( -- )
   TASK-STRLEN-XT @ 0= 0= if exit then
   TASK-LIB-PATH RTLD-NOW DLOPEN dup 0= if E-TASK-DLOPEN throw then
   TASK-SYM-STRLEN DLSYM dup 0= if E-TASK-DLSYM throw then
   TASK-STRLEN-XT ! ;

: TASK-CSTRLEN ( ptr u8 -- n ) {: cstr:ptr :}
   cstr P>N 0 FFI-ARG!
   TASK:PAUSE
   1 TASK-STRLEN-XT @ FFI-CALLN ;

: ODIN-BAD+ ( -- )
   1 ODIN-BAD atomic-add drop ;

: ODIN-WAIT-CELL ( ptr a n -- ) {: cell:ptr want:n :}
   begin cell atomic@ want < while TASK:PAUSE repeat ;

: ODIN-WAIT-DONE ( ptr a -- ) {: tcb:ptr :}
   begin tcb TASK:DONE? 0= while TASK:PAUSE repeat ;

: ODIN-SHARED+ ( n -- ) {: v:n :}
   ODIN-LOCK TASK:GET
   ODIN-SHARED @ v + ODIN-SHARED !
   ODIN-LOCK TASK:RELEASE ;

: ODIN-ACQ-WORK ( n ptr u8 n -- ) {: id:n cstr:ptr want:n :}
   id TASK-LOCAL-ID !
   0 TASK-LOCAL-FFI !
   ODIN-ITERS 0 ?do
      id TASK-LOCAL-ID !
      cstr TASK-CSTRLEN dup TASK-LOCAL-FFI !
      dup want <> if ODIN-BAD+ then
      ODIN-FFI-TOTAL atomic-add drop
      TASK-LOCAL-ID @ id <> if ODIN-BAD+ then
      id 1 + ODIN-SHARED+
   loop
   1 ODIN-ACQ-DONE atomic-add drop ;

: ODIN-ACQ0-WORK ( -- )
   0 ODIN-CSTR1 1 ODIN-ACQ-WORK ;

: ODIN-ACQ1-WORK ( -- )
