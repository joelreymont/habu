\ Bounded ELF32 decoding through the native checked public interface.
require lib/elf32.f
require lib/test.f
require test/checker-assert.f

package ELF32-TEST
private
using ELF32

create INPUT $100 allot
CAST: BLEN>N ( NUM:byte-len -- n )

: RESET ( -- )
   S\" \x7f\x45\x4c\x46\x01\x01\x01\x00\x00\x00\x00\x00\x00\x00\x00\x00\x02\x00\x28\x00\x01\x00\x00\x00\x01\x00\x00\x80\x34\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x05\x34\x00\x20\x00\x02\x00\x00\x00\x00\x00\x00\x00\x01\x00\x00\x00\x80\x00\x00\x00\x00\x00\x00\x80\x00\x00\x00\x88\x05\x00\x00\x00\x08\x00\x00\x00\x05\x00\x00\x00\x10\x00\x00\x00\x01\x00\x00\x00\x90\x00\x00\x00\x10\x00\x00\x80\x10\x00\x00\x88\x00\x00\x00\x00\x10\x00\x00\x00\x06\x00\x00\x00\x10\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x2a\x00\x00\x00\xff\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00" INPUT swap >LEN BYTE-COPY-LEN ;

: U32! ( n n -- ) {: value:n offset:n :}
   4 0 do value i 8 * rshift $FF and INPUT offset + i + c! loop ;

: SPAN ( -- ptr u8 NUM:byte-len )
   INPUT $90 FILE-BYTES ;

: HEADER-CASE ( -- )
   SPAN INFO ELF32-HEADER:UNMAKE
   PROGRAM-COUNT>N 2 T= 0 T= 0 T= $05000000 T=
   ADDRESS>N $80000001 T= MACHINE-ID>N 40 T= FILE-KIND>N 2 T= ;

: LOAD-CASE ( -- )
   SPAN 0 >PROGRAM-INDEX PROGRAM ELF32-SEGMENT:UNMAKE
   $10 T= 5 T= BLEN>N 8 T=
   ADDRESS>N $88000000 T= ADDRESS>N $80000000 T= SEGMENT-KIND>N 1 T=
   BLEN>N S\" \x2a\x00\x00\x00\xff" T$= ;

: BSS-CASE ( -- )
   SPAN 1 >PROGRAM-INDEX PROGRAM ELF32-SEGMENT:UNMAKE
   $10 T= 6 T= BLEN>N $10 T=
   ADDRESS>N $88000010 T= ADDRESS>N $80000010 T= SEGMENT-KIND>N 1 T=
   BLEN>N 0 T= INPUT = TTRUE ;

: VALID ( -- ) SPAN VALIDATE ;
: DROP-HEADER ( ELF32:header -- ) ELF32-HEADER:UNMAKE 2drop 2drop 2drop drop ;
: DROP-SEGMENT ( ELF32:segment -- ) ELF32-SEGMENT:UNMAKE 2drop 2drop 2drop 2drop ;

: TRUNCATED ( n -- )
   [: dup INPUT swap FILE-BYTES VALIDATE ;] catch E-BOUNDS T= drop ;

: HEADER-REFUSALS ( -- )
   RESET 0 INPUT c! [: VALID ;] E-FORMAT TTHROWSQ
   RESET 2 INPUT 4 + c! [: VALID ;] E-UNSUPPORTED TTHROWSQ
   RESET 2 INPUT 5 + c! [: VALID ;] E-UNSUPPORTED TTHROWSQ
   RESET 2 INPUT 6 + c! [: VALID ;] E-UNSUPPORTED TTHROWSQ
   RESET 2 $14 U32! [: VALID ;] E-UNSUPPORTED TTHROWSQ
   RESET $33 INPUT $28 + c! [: VALID ;] E-FORMAT TTHROWSQ
   RESET $FF INPUT $29 + c! [: VALID ;] E-BOUNDS TTHROWSQ
   RESET $34 0 do i TRUNCATED loop ;

: TABLE-REFUSALS ( -- )
   RESET $1F INPUT $2A + c! [: VALID ;] E-FORMAT TTHROWSQ
   RESET 0 $1C U32! [: VALID ;] E-FORMAT TTHROWSQ
   RESET $FFFFFFF0 $1C U32! [: VALID ;] E-BOUNDS TTHROWSQ
   RESET $73 TRUNCATED
   RESET $FFFF INPUT $2C + c! $FF INPUT $2D + c!
   [: VALID ;] E-UNSUPPORTED TTHROWSQ ;

: PAYLOAD-REFUSALS ( -- )
   RESET $8C $38 U32! 0 $50 U32! [: VALID ;] E-BOUNDS TTHROWSQ
   RESET $FFFFFFFF $38 U32! [: VALID ;] E-BOUNDS TTHROWSQ
   RESET 4 $48 U32! [: VALID ;] E-FORMAT TTHROWSQ
   RESET $FFFFFFFC $3C U32! 0 $50 U32! [: VALID ;] E-BOUNDS TTHROWSQ
   RESET 3 $50 U32! [: VALID ;] E-FORMAT TTHROWSQ
   RESET $81 $38 U32! [: VALID ;] E-FORMAT TTHROWSQ ;

: INDEX-REFUSALS ( -- )
   RESET
   [: SPAN -1 >PROGRAM-INDEX PROGRAM DROP-SEGMENT ;] E-BOUNDS TTHROWSQ
   [: SPAN 2 >PROGRAM-INDEX PROGRAM DROP-SEGMENT ;] E-BOUNDS TTHROWSQ
   [: -1 FILE-BYTES drop ;] E-BOUNDS TTHROWSQ ;

: EMPTY-AND-EXTENDED ( -- )
   RESET 0 INPUT $2C + c! 0 INPUT $2A + c! $FFFFFFFF $1C U32!
   INPUT $34 FILE-BYTES VALIDATE
   INPUT $34 FILE-BYTES INFO ELF32-HEADER:UNMAKE
   PROGRAM-COUNT>N 0 T= 2drop 2drop 2drop
   RESET
   INPUT $80 + INPUT $A0 + 5 >LEN BYTE-COPY-LEN
   INPUT $54 + INPUT $C0 + $20 >LEN BYTE-COPY-LEN
   INPUT $34 + INPUT $E0 + $20 >LEN BYTE-COPY-LEN
   INPUT $C0 + INPUT $68 + $20 >LEN BYTE-COPY-LEN
   INPUT $E0 + INPUT $40 + $20 >LEN BYTE-COPY-LEN
   $A0 $44 U32! $B0 $6C U32!
   $40 $1C U32! $40 INPUT $28 + c! $28 INPUT $2A + c!
   INPUT $B0 FILE-BYTES VALIDATE
   INPUT $B0 FILE-BYTES 0 >PROGRAM-INDEX PROGRAM ELF32-SEGMENT:UNMAKE
   2drop 2drop 2drop BLEN>N S\" \x2a\x00\x00\x00\xff" T$= ;

: SEGMENT-SCOPE ( -- )
   RESET 0 $50 U32! VALID
   RESET 1 $50 U32! VALID
   RESET $FFFFFFFF $58 U32! 0 $70 U32! VALID
   RESET $FFFFFFF8 $3C U32! 0 $50 U32! VALID
   RESET $FFFFFFFF $40 U32! VALID
   RESET 4 $34 U32! 0 $48 U32! 3 $50 U32! VALID
   RESET 0 $54 U32! $FFFFFFFF $58 U32! $FFFFFFFF $64 U32! VALID
   SPAN 1 >PROGRAM-INDEX PROGRAM ELF32-SEGMENT:UNMAKE
   2drop 2drop drop SEGMENT-KIND>N 0 T= BLEN>N 0 T= INPUT = TTRUE
   RESET $FFFFFFFF $58 U32! 1 $64 U32!
   SPAN INFO DROP-HEADER
   SPAN 0 >PROGRAM-INDEX PROGRAM DROP-SEGMENT
   [: VALID ;] E-BOUNDS TTHROWSQ
   [: SPAN 1 >PROGRAM-INDEX PROGRAM DROP-SEGMENT ;] E-BOUNDS TTHROWSQ ;

: NOMINAL-CASES ( -- )
   s" ELF32-GOOD ( ELF32:address -- ELF32:address )" CHECK-QUIET-CANDIDATE! -1 T=
   s" ELF32-BAD-ADDR ( n -- ELF32:address )" CHECK-QUIET-CANDIDATE! 0 T=
   s" ELF32-BAD-INDEX ( ELF32:program-count -- ELF32:program-index )"
      CHECK-QUIET-CANDIDATE! 0 T= ;

: RUN ( -- )
   RESET VALID HEADER-CASE LOAD-CASE BSS-CASE
   HEADER-REFUSALS TABLE-REFUSALS PAYLOAD-REFUSALS INDEX-REFUSALS
   EMPTY-AND-EXTENDED SEGMENT-SCOPE NOMINAL-CASES T-REPORT ;

RUN
;package
