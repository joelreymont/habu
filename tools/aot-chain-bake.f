\ aot-chain-bake.f - bake ONE named chain artifact into an engine.
\
\ The production build captures its own artifact and bakes it (tools/build-fixpoint.f
\ BF-BUILD-STDIN-FROM-STAGE), so this tool is not how bin/hb is made. It exists for
\ the case the build cannot serve: baking an artifact somebody else captured, keyed
\ to the engine that captured it, without a capture of its own. That is what the
\ acceptance suite needs - it captures in bin/hb, edits the bytes, and asks what the
\ real bake does with them.
\
\ Everything below the argument handling is the production path: the driver is
\ generated by BUILD-FIXPOINT (which owns the build's path construction) and the
\ engine is emitted by the same BF-EMIT-ENGINE the build calls twice.
\
\ Run:  bin/hb --load tools/aot-chain-bake.f -- <artifact> <producer-engine>
\ Leaves <HB_TMP>/hb-chain and prints `aot-chain-bake: hb-chain ready`.

