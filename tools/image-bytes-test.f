: IBT-CHECK-REJECTS ( str -- )
   CHECK-QUIET-CANDIDATE! 0 T= ;

\ A size rounds up to 64 KiB. A larger one maps a fresh, zeroed buffer at the
\ next use; an equal or smaller one keeps the mapped buffer and its bytes.
: IBT-TEST-MSIZE ( -- )
   IMAGE-BYTES:MSIZE $10000 + {: grown:n :}
   grown 1 - IMAGE-BYTES:MSIZE!  IMAGE-BYTES:MSIZE grown T=
   IMAGE-BYTES:M-RESET  7 IMAGE-BYTES:IMG-M8  IMAGE-BYTES:MBUF c@ 7 T=
   grown IMAGE-BYTES:MSIZE!  IMAGE-BYTES:MSIZE grown T=  IMAGE-BYTES:MBUF c@ 7 T=
   1 IMAGE-BYTES:MSIZE!  IMAGE-BYTES:MSIZE grown T=  IMAGE-BYTES:MBUF c@ 7 T=
   grown 1 + IMAGE-BYTES:MSIZE!  IMAGE-BYTES:MSIZE grown $10000 + T=  IMAGE-BYTES:MBUF c@ 0 T=
   IMAGE-BYTES:M-RESET  IMAGE-BYTES:MSIZE 1- IMAGE-BYTES:M-OFF IMAGE-BYTES:M-PAD-OFF  1 IMAGE-BYTES:IMG-M8  IMAGE-BYTES:M-HERE IMAGE-BYTES:MSIZE T= ;

: IBT-TEST-LITTLE-ENDIAN ( -- )
   IMAGE-BYTES:M-RESET
   $12 IMAGE-BYTES:IMG-M8
   $3456 IMAGE-BYTES:IMG-M16
   $789ABCDE IMAGE-BYTES:IMG-M32
   $1122334455667788 IMAGE-BYTES:IMG-M64
   IMAGE-BYTES:M-HERE 15 T=
   3 IMAGE-BYTES:M-OFF IMAGE-BYTES:M-LE32@ $789ABCDE T=
   $AABBCCDD 2 IMAGE-BYTES:M-OFF IMAGE-BYTES:M-LE32!
   2 IMAGE-BYTES:M-OFF IMAGE-BYTES:M-LE32@ $AABBCCDD T=
   $1122334455667788 8 IMAGE-BYTES:M-OFF IMAGE-BYTES:M-LE64!
   8 IMAGE-BYTES:M-OFF IMAGE-BYTES:M-LE32@ $55667788 T=
   12 IMAGE-BYTES:M-OFF IMAGE-BYTES:M-LE32@ $11223344 T= ;

: IBT-TEST-COPY-PAD ( -- )
   IMAGE-BYTES:M-RESET
   s" habu" IMAGE-BYTES:M-BYTES
   IMAGE-BYTES:M-HERE 4 T=
   8 IMAGE-BYTES:M-OFF IMAGE-BYTES:M-PAD-OFF
   IMAGE-BYTES:M-HERE 8 T=
   s" xy" IMAGE-BYTES:M-NAME16
   IMAGE-BYTES:M-HERE 24 T=
   IMAGE-BYTES:MBUF 8 + c@ 120 T=
   IMAGE-BYTES:MBUF 9 + c@ 121 T=
   IMAGE-BYTES:MBUF 23 + c@ 0 T= ;

: IBT-TEST-BIG-ENDIAN ( -- )
   IMAGE-BYTES:M-RESET
   16 IMAGE-BYTES:M-OFF IMAGE-BYTES:M-BE-RESET
   $01020304 IMAGE-BYTES:M-BE32
   $05060708090A0B0C IMAGE-BYTES:M-BE64
   s" Z" IMAGE-BYTES:M-BE-BYTES
   IMAGE-BYTES:M-BE-HERE 29 T=
   IMAGE-BYTES:MBUF 16 + c@ 1 T=
   IMAGE-BYTES:MBUF 17 + c@ 2 T=
   IMAGE-BYTES:MBUF 18 + c@ 3 T=
   IMAGE-BYTES:MBUF 19 + c@ 4 T=
   IMAGE-BYTES:MBUF 27 + c@ 12 T=
   IMAGE-BYTES:MBUF 28 + c@ 90 T= ;

: IBT-LEN-NEG ( -- )
   -1 IMAGE-BYTES:M-LEN drop ;

: IBT-OFF-NEG ( -- )
   -1 IMAGE-BYTES:M-OFF drop ;

: IBT-PAD-BACK ( -- )
   IMAGE-BYTES:M-RESET
   4 IMAGE-BYTES:IMG-M8
   0 IMAGE-BYTES:M-OFF IMAGE-BYTES:M-PAD-OFF ;

: IBT-NAME-LONG ( -- )
   IMAGE-BYTES:M-RESET
   s" 12345678901234567" IMAGE-BYTES:M-NAME16 ;

: IBT-FILL-OVER ( -- )
   s" xy" IMAGE-BYTES:M-BYTES ;

: IBT-FILL-EXACT ( -- )
   s" x" IMAGE-BYTES:M-BYTES ;

: IBT-CURSOR-OVER ( -- )
   1 IMAGE-BYTES:IMG-M8 ;

: IBT-WRITE-NEG ( -- )
   IMAGE-BYTES:M-RESET 1 IMAGE-BYTES:IMG-M8
   s" x" STR:DATA -1 >str IMAGE-BYTES:M-BYTES ;

: IBT-WRITE-MAX ( -- )
   IMAGE-BYTES:M-RESET 1 IMAGE-BYTES:IMG-M8
   s" x" STR:DATA -1 1 rshift >str IMAGE-BYTES:M-BYTES ;

\ One pad to the last byte serves the three room boundaries in turn. A write is
\ measured against the room left: `>LEN` is a cast, not a validator, and a length
\ near the maximum cell would wrap the sum back under MSIZE. A rejected write
\ leaves the cursor in place, so the exact write after it fills the buffer; a
\ cursor at MSIZE throws 88.
: IBT-TEST-ROOM ( -- )
   IMAGE-BYTES:M-RESET  IMAGE-BYTES:MSIZE 1- IMAGE-BYTES:M-OFF IMAGE-BYTES:M-PAD-OFF
   [: IBT-FILL-OVER ;] EXIT-STATUS:IMAGE-BOUNDS TTHROWSQ
   IBT-FILL-EXACT IMAGE-BYTES:M-HERE IMAGE-BYTES:MSIZE T=
   [: IBT-CURSOR-OVER ;] EXIT-STATUS:IMAGE-BOUNDS TTHROWSQ
   [: IBT-WRITE-NEG ;] EXIT-STATUS:IMAGE-BOUNDS TTHROWSQ
   IMAGE-BYTES:M-HERE 1 T=
   [: IBT-WRITE-MAX ;] EXIT-STATUS:IMAGE-BOUNDS TTHROWSQ
   IMAGE-BYTES:M-HERE 1 T= ;

: IBT-TEST-REFINE-ERRORS ( -- )
   [: IBT-LEN-NEG ;] EXIT-STATUS:IMAGE-BOUNDS TTHROWSQ
   [: IBT-OFF-NEG ;] EXIT-STATUS:IMAGE-BOUNDS TTHROWSQ
   [: IBT-PAD-BACK ;] EXIT-STATUS:IMAGE-BOUNDS TTHROWSQ
   [: IBT-NAME-LONG ;] EXIT-STATUS:IMAGE-BOUNDS TTHROWSQ
   s" BAD-M-LE32 ( len -- n ) M-LE32@" IBT-CHECK-REJECTS
   s" BAD-M-PAD ( len -- ) M-PAD-OFF" IBT-CHECK-REJECTS ;

