\ class-generate.f - deterministic Unicode character-class source generator.

require src/lib/prelude.f
require src/lib/memory.f
require src/lib/fs.f
require src/lib/fs-mutate.f
require src/lib/codegen.f
require tools/unicode/class-parse.f

package UNICODE-CLASS-TOOL

private

131072 CODEGEN:BUFFER OUTPUT
10 constant OUTPUT-LINE-FEED
64 constant SHA256-HEX-LENGTH
create INPUT-DIGEST SHA256-HEX-LENGTH allot
create UC-FSHA-CTX SHA256-FILE-CTX-BYTES allot   \ this tool's file-digest context

: UNICODE-PATH$ ( -- ptr u8 n )
   s" data/unicode/16.0.0/UnicodeData.txt" ;

: PROPERTIES-PATH$ ( -- ptr u8 n )
   s" data/unicode/16.0.0/PropList.txt" ;

: OUTPUT-PATH$ ( -- ptr u8 n )
   s" src/lib/unicode/class-data.f" ;

: EXPECTED-UNICODE-DIGEST$ ( -- ptr u8 n )
   s" ff58e5823bd095166564a006e47d111130813dcf8bf234ef79fa51a870edb48f" ;

: EXPECTED-PROPERTIES-DIGEST$ ( -- ptr u8 n )
   s" 53d614508e2a0b2305a8aa21cd60d993de9326cdf65993660dfcce4503548583" ;

: VERIFY-FILE-DIGEST ( ptr u8 n ptr u8 n -- ) {: path:ptr pathu:n want:ptr wantu:n :}
   wantu SHA256-HEX-LENGTH <> if E-DIGEST throw then
   UC-FSHA-CTX path pathu INPUT-DIGEST SHA256-FILE-HEX-IN 0 <> if E-DIGEST throw then
   INPUT-DIGEST SHA256-HEX-LENGTH want wantu STR= 0= if E-DIGEST throw then ;

: CHECK-INPUT-DIGESTS ( -- )
   UNICODE-PATH$ EXPECTED-UNICODE-DIGEST$ VERIFY-FILE-DIGEST
   PROPERTIES-PATH$ EXPECTED-PROPERTIES-DIGEST$ VERIFY-FILE-DIGEST ;

: LOAD-UNICODE-FILE ( -- )
   UNICODE-PATH$ 2dup FILE-SIZE 1+ MEM-ALLOC-64K-SPAN {: path:ptr pathu:n buf:ptr cap:n :}
   path pathu buf cap READ-ALL {: got:n :}
   buf got PARSE-UNICODE ;

: LOAD-PROPERTIES-FILE ( -- )
   PROPERTIES-PATH$ 2dup FILE-SIZE 1+ MEM-ALLOC-64K-SPAN {: path:ptr pathu:n buf:ptr cap:n :}
   path pathu buf cap READ-ALL {: got:n :}
   buf got PARSE-PROPERTIES ;

: OUT$ ( ptr u8 n -- )
   OUTPUT CODEGEN:APPEND-STRING ;

: OUT-N ( n -- )
   OUTPUT CODEGEN:APPEND-DECIMAL ;

: OUT-LINE ( ptr u8 n -- )
   OUT$
   OUTPUT-LINE-FEED OUTPUT CODEGEN:APPEND-BYTE ;

: OUT-RANGE ( n n -- ) {: lo:n hi:n :}
   s"    " OUT$ lo OUT-N s"  " OUT$ hi OUT-N s"  R," OUT-LINE ;

: OUT-RANGES ( n [ n -- n n ] -- ) {: count:n getter :}
   0 begin dup count < while
      dup getter execute OUT-RANGE
      1+
   repeat drop ;

: OUT-TABLE ( ptr u8 n n [ n -- n n ] -- )
   {: name:ptr nameu:n count:n getter :}
   count OUT-N s"  constant " OUT$ name nameu OUT$ s" -TABLE-COUNT" OUT-LINE
   \ Empty logical tables still need a valid private typed buffer.
   count 2 * 1 max OUT-N s"  TYPED-BUFFER " OUT$ name nameu OUT$ s" -TABLE n" OUT-LINE
   s" 0 " OUT$ name nameu OUT$ s" -TABLE" OUT-LINE
   count getter OUT-RANGES
   s" drop" OUT-LINE
   s" " OUT-LINE ;

: OUT-PREAMBLE ( -- )
   s" \ class-data.f - generated complete Unicode 16.0.0 class ranges." OUT-LINE
   s" \ Generated by tools/unicode/class-generate.f; do not edit." OUT-LINE
   s" \ Each table holds sorted, disjoint, inclusive first and last cell pairs." OUT-LINE
   s" " OUT-LINE
   s" require src/lib/prelude.f" OUT-LINE
   s" " OUT-LINE
   s" package UNICODE-CLASS-DATA" OUT-LINE
   s" " OUT-LINE
   s" private" OUT-LINE
   s" " OUT-LINE
   s" \ R, stores one range at the fill cursor and answers the cursor past it." OUT-LINE
   s" : R, ( ptr n n n -- ptr n )" OUT-LINE
   s"    {: at:ptr lo:n hi:n :}" OUT-LINE
   s"    lo at ! hi at cell+ !" OUT-LINE
   s"    at 2 cells + ;" OUT-LINE
   s" " OUT-LINE ;

: OUT-PUBLIC ( -- )
   s" public" OUT-LINE
   s" " OUT-LINE ;

\ An accessor answers its table's first cell and range count together.
: OUT-ACCESSOR ( ptr u8 n -- ) {: name:ptr nameu:n :}
   s" : " OUT$ name nameu OUT$ s" -RANGES ( -- ptr n n )" OUT-LINE
   s"    0 " OUT$ name nameu OUT$ s" -TABLE " OUT$
   name nameu OUT$ s" -TABLE-COUNT ;" OUT-LINE
   s" " OUT-LINE ;

: OUT-ACCESSORS ( -- )
   s" LETTER" OUT-ACCESSOR
   s" NUMBER" OUT-ACCESSOR
   s" WHITE-SPACE" OUT-ACCESSOR
   s" LETTER-NUMBER" OUT-ACCESSOR
   s" OTHER-ALPHABETIC" OUT-ACCESSOR
   s" UPPERCASE-LETTER" OUT-ACCESSOR
   s" OTHER-UPPERCASE" OUT-ACCESSOR
   s" ;package" OUT-LINE ;

public

: CHECK-FILE-DIGEST ( ptr u8 n ptr u8 n -- )
   VERIFY-FILE-DIGEST ;

: LOAD-PINNED ( -- )
   CHECK-INPUT-DIGESTS
   RESET
   LOAD-UNICODE-FILE
   LOAD-PROPERTIES-FILE
   READY? 0= if E-STATE throw then ;

: RENDER ( -- ptr u8 n )
   READY? 0= if E-STATE throw then
   OUTPUT CODEGEN:RESET
   OUT-PREAMBLE
   s" LETTER" LETTER-COUNT [: LETTER-RANGE@ ;] OUT-TABLE
   s" NUMBER" NUMBER-COUNT [: NUMBER-RANGE@ ;] OUT-TABLE
   s" WHITE-SPACE" SPACE-COUNT [: SPACE-RANGE@ ;] OUT-TABLE
   s" LETTER-NUMBER" LETTER-NUMBER-COUNT [: LETTER-NUMBER-RANGE@ ;] OUT-TABLE
   s" OTHER-ALPHABETIC" OTHER-ALPHABETIC-COUNT [: OTHER-ALPHABETIC-RANGE@ ;] OUT-TABLE
   s" UPPERCASE-LETTER" UPPERCASE-LETTER-COUNT [: UPPERCASE-LETTER-RANGE@ ;] OUT-TABLE
   s" OTHER-UPPERCASE" OTHER-UPPERCASE-COUNT [: OTHER-UPPERCASE-RANGE@ ;] OUT-TABLE
   OUT-PUBLIC
   OUT-ACCESSORS
   OUTPUT CODEGEN:CONTENTS ;

: WRITE-PINNED ( -- )
   LOAD-PINNED
   OUTPUT-PATH$ RENDER ATOMIC-WRITE-FILE ;

;package
