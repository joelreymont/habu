      {: cancelled:r cancel-error:r :}
   cancelled 0.0 f= TTRUE
   cancel-error -53 F2-N f>= TTRUE

   -1.0 0.0 -53 F2-N 0.0 FMATH:SUB-BOUND
      {: negative:r negative-error:r :}
   negative -1.0 f= TTRUE
   negative-error -53 F2-N f>= TTRUE

