\ FMAX, then FMIN, of the operands a and b is want, compared by bits.
\ Which NaN a sum of two NaNs gives is the machine's (IEEE 754 6.2.3), so a
\ NaN result is held only to being quiet, as FMAX and FMIN promise.
: SAME-BITS ( n n -- ) {: got:n want:n :}
   want QNAN and QNAN = if got QNAN and QNAN = TTRUE exit then
   got want T= ;
: MAX= ( n n n -- ) {: a:n b:n want:n :}
   a IEEE754:BITS>F64 b IEEE754:BITS>F64 FMATH:FMAX IEEE754:F64>BITS want SAME-BITS ;
: MIN= ( n n n -- ) {: a:n b:n want:n :}
   a IEEE754:BITS>F64 b IEEE754:BITS>F64 FMATH:FMIN IEEE754:F64>BITS want SAME-BITS ;

