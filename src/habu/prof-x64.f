\ Add one to the cell `off` past the register. It clobbers rcx.
: BUMP, ( X64ASM:r64 n -- ) {: base:X64ASM:r64 off:n :}
   X64ASM:RCX base off X64ASM:MEM-OFF LOAD,  X64ASM:RCX INC,  X64ASM:RCX base off X64ASM:MEM-OFF STORE, ;

: ARENA>RSI, ( -- )  X64ASM:RSI BAND-VA IMM,  X64ASM:RSI X64ASM:RSI PROF-ABI:PROF-ARENA X64ASM:MEM-OFF LOAD, ;

\ The handler and the replay keep the sample's weight at [rsp]: r = the
\ weight `at` bytes above rsp.
: WEIGHT, ( X64ASM:r64 n -- ) {: r:X64ASM:r64 at:n :}  r X64ASM:RSP at X64ASM:MEM-OFF LOAD, ;

\ Add r to the cell `off` past base.
: ADD-MEM, ( X64ASM:r64 X64ASM:r64 n -- ) {: r:X64ASM:r64 base:X64ASM:r64 off:n :}
   r base off X64ASM:MEM-OFF X64CODE:ASM-SINK X64ASM:ENC-ADD-MR ;

\ Add the weight at [rsp] to the cell `off` past the register. It clobbers rcx.
: ADD-WEIGHT, ( X64ASM:r64 n -- ) {: base:X64ASM:r64 off:n :}  X64ASM:RCX 0 WEIGHT,  X64ASM:RCX base off ADD-MEM, ;

\ rax = ns on CLOCK_MONOTONIC, ITIMER_REAL's clock, by the system call, which
\ a signal handler may make. rsi and rdi survive; clobbers rcx r11.
