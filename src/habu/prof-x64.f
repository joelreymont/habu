   s\" ,\"edges\":[" SAY,
   X64ASM:R12 ZERO-REG,
   X64ASM:RBX X64ASM:R15 PROF-ABI:ARN-CALL X64ASM:MEM-OFF LEA,  X64ASM:R13 PROF-ABI:PROF-CALL-SLOTS IMM32,
   turn X64CODE:LBL,
      X64ASM:R13 TEST,  X64ASM:C-E done X64CODE:JCC,
      X64ASM:RAX X64ASM:RBX X64ASM:MEM-AT LOAD,  X64ASM:RAX TEST,  X64ASM:C-E next X64CODE:JCC,
      X64ASM:R12 TEST,  X64ASM:C-E first X64CODE:JCC,  s" ," SAY,
      first X64CODE:LBL,  X64ASM:R12 1 IMM32,
      s\" {\"word\":\"" SAY,
      X64ASM:R9 X64ASM:RBX X64ASM:MEM-AT LOAD,  X64ASM:R9 DEC,  X64ASM:R9 PROF-ABI:PROF-REC-BITS X64ASM:>IMM8 X64CODE:ASM-SINK X64ASM:ENC-SHR-RI8
