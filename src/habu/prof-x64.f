\ mov r32, imm32, which zero-extends: a small non-negative count or number.
: IMM32, ( X64ASM:r64 n -- ) {: r:X64ASM:r64 v:n :}
   r X64ASM:R64>N X64ASM:>R32 v X64ASM:>IMM32 X64CODE:ASM-SINK X64ASM:ENC-MOV32-RI32 ;

