   \ + ARN-SPILL + PROF-OTHER + PROF-FOREIGN == PROF-TOT whenever no tick runs.
   lost X64CODE:LBL,  PROF-ABI:PROF-FOREIGN BAND-ADD,
   ftotal X64CODE:LBL,  PROF-ABI:PROF-TOT BAND-ADD,   \ no LIMIT: a limit a foreign sample reaches reports at the next Habu one
   out X64CODE:LBL,  X64ASM:RCX X64CODE:ASM-SINK X64ASM:ENC-POP
   X64CODE:RET,
   total X64CODE:LBL,  PROF-ABI:PROF-TOT BAND-ADD,
   LIMIT,
   X64ASM:RCX X64CODE:ASM-SINK X64ASM:ENC-POP
   X64CODE:RET, ;

\ Everything a report prints goes through these, so a row, a caller line and a
\ JSON field agree about widths and about where a name comes from: the twins
\ of prof.f's printers. Each writes fd 1 directly, as those do.

: SAY, ( str -- ) {: t:str :}
   X64CODE:LBL {: text:label :}
   text t X64CODE:DATA-AFTER
   X64ASM:RDI STDOUT IMM32,  X64ASM:RSI text X64CODE:MOVABS,  X64ASM:RDX t STR:LEN IMM32,  NR-WRITE SYS, ;

\ Write the one byte, from a cell pushed for it.
: BYTE, ( n -- ) {: c:n :}
   X64ASM:RAX c IMM32,  X64ASM:RAX X64CODE:ASM-SINK X64ASM:ENC-PUSH
   X64ASM:RDI STDOUT IMM32,  X64ASM:RSI X64ASM:RSP COPY,  X64ASM:RDX 1 IMM32,  NR-WRITE SYS,
   X64ASM:RSP CELL X64ASM:>IMM8 X64CODE:ASM-SINK X64ASM:ENC-ADD-RI8 ;

: NL, ( -- ) s\" \n" SAY, ;
: DQ, ( -- ) s\" \q" SAY, ;

\ NUM ( rax = value, r8 = width ): unsigned decimal, right-aligned in r8
\ columns and never truncated, no newline: the twin of prof.f LPROFNUM. The
\ padding lands in the frame the digits do, so one write puts out the column.
: NUM-HELPER, ( -- )
   NUM-LBL X64CODE:LBL,
   X64CODE:LBL X64CODE:LBL {: pad:label done:label :}
   X64ASM:RSP NUM-BYTES X64ASM:>IMM8 X64CODE:ASM-SINK X64ASM:ENC-SUB-RI8
   X64ASM:RSI X64ASM:RSP NUM-BYTES X64ASM:MEM-OFF LEA,
   X64RT:DIGITS,                                                       \ rsi = the first digit
   X64ASM:RDX X64ASM:RSP NUM-BYTES X64ASM:MEM-OFF LEA,  X64ASM:RDX X64ASM:RSI X64CODE:ASM-SINK X64ASM:ENC-SUB-RR
   X64ASM:R8 X64ASM:RDX X64CODE:ASM-SINK X64ASM:ENC-SUB-RR                                    \ the columns the digits leave
   X64ASM:RCX STR:SPACE IMM32,
   pad X64CODE:LBL,
      X64ASM:R8 TEST,  X64ASM:C-LE done X64CODE:JCC,
      X64ASM:RSI DEC,  X64ASM:RCX X64ASM:R64>N X64ASM:>R8 X64ASM:RSI X64ASM:MEM-AT X64CODE:ASM-SINK X64ASM:ENC-MOV8-MR
      X64ASM:R8 DEC,  pad X64CODE:JMP,
   done X64CODE:LBL,
   X64ASM:RDX X64ASM:RSP NUM-BYTES X64ASM:MEM-OFF LEA,  X64ASM:RDX X64ASM:RSI X64CODE:ASM-SINK X64ASM:ENC-SUB-RR
   X64ASM:RDI STDOUT IMM32,  NR-WRITE SYS,
   X64ASM:RSP NUM-BYTES X64ASM:>IMM8 X64CODE:ASM-SINK X64ASM:ENC-ADD-RI8
   X64CODE:RET, ;

\ rax = the value, printed in n columns.
: NUM, ( n -- ) {: w:n :}  X64ASM:R8 w IMM32,  NUM-LBL X64CODE:CALL, ;

\ PCT ( rax = count, r8 = total ): the share in tenths of a percent, as
\ "100.0" right-aligned in six columns; a zero total prints 0.0 rather than
\ dividing by it: the twin of prof.f LPROFPCT, whose product wraps as this
\ one does.
: PCT-HELPER, ( -- )
   PCT-LBL X64CODE:LBL,
   X64CODE:LBL X64CODE:LBL {: zero:label go:label :}
   X64ASM:R8 TEST,  X64ASM:C-E zero X64CODE:JCC,
   X64ASM:RAX X64ASM:RAX 1000 X64ASM:>IMM32 X64CODE:ASM-SINK X64ASM:ENC-IMUL-RRI32
   X64ASM:RDX ZERO-REG,  X64ASM:R8 X64CODE:ASM-SINK X64ASM:ENC-DIV
   go X64CODE:JMP,
   zero X64CODE:LBL,  X64ASM:RAX ZERO-REG,
   go X64CODE:LBL,
   X64ASM:RCX 10 IMM32,  X64ASM:RDX ZERO-REG,  X64ASM:RCX X64CODE:ASM-SINK X64ASM:ENC-DIV            \ rax the whole percent, rdx the tenth
   X64ASM:RDX X64CODE:ASM-SINK X64ASM:ENC-PUSH
   4 NUM,
   [char] . BYTE,
   X64ASM:RAX X64CODE:ASM-SINK X64ASM:ENC-POP  1 NUM,
   X64CODE:RET, ;

\ NAME ( rdi = profile row ): the complete copied qualified name.
: NAME-HELPER, ( -- )
   NAME-LBL X64CODE:LBL,
   X64ASM:RDX X64ASM:RDI PROF-ABI:RID-LEN X64ASM:MEM-OFF LOAD,
   X64ASM:RSI X64ASM:RDI PROF-ABI:RID-NAME X64ASM:MEM-OFF LOAD,
   X64ASM:RDI STDOUT IMM32,  NR-WRITE SYS,
   X64CODE:RET, ;

\ rdi = an owned profile row: its qualified name.
: NAMED, ( -- )  NAME-LBL X64CODE:CALL, ;

\ Reports keep RBX as a stable profile ID and R15 as the arena; printed
\ columns may clobber scratch registers. Retired IDs retain names and counts.
0 constant AT-SAMPLES                   \ PROF-TOT, read once
8 constant AT-EXCL                      \ the row's exclusive count
16 constant AT-DENOM                    \ what its caller shares are of
24 constant AT-RANK                     \ the caller rank
32 constant AT-CAP                      \ the caller count the next line must fall under,
40 constant AT-CAP-SLOT                 \ or match at a later edge slot than this one
48 constant AT-REC                      \ the caller line's record, 0 for none
56 constant AT-N                        \ the caller line's count
64 constant AT-WORDS                    \ samples attributed to a word
72 constant AT-ATTR                     \ profile IDs either count reached
80 constant FRAME-BYTES

: SLOT@, ( X64ASM:r64 n -- ) {: r:X64ASM:r64 off:n :}  r X64ASM:RSP off X64ASM:MEM-OFF LOAD, ;
: SLOT!, ( X64ASM:r64 n -- ) {: r:X64ASM:r64 off:n :}  r X64ASM:RSP off X64ASM:MEM-OFF STORE, ;

: OPEN, ( -- )
   X64ASM:RBX X64CODE:ASM-SINK X64ASM:ENC-PUSH  X64ASM:R12 X64CODE:ASM-SINK X64ASM:ENC-PUSH  X64ASM:R13 X64CODE:ASM-SINK X64ASM:ENC-PUSH
   X64ASM:R14 X64CODE:ASM-SINK X64ASM:ENC-PUSH  X64ASM:R15 X64CODE:ASM-SINK X64ASM:ENC-PUSH
   X64ASM:RSP FRAME-BYTES X64ASM:>IMM8 X64CODE:ASM-SINK X64ASM:ENC-SUB-RI8 ;

: CLOSE, ( -- )
   X64ASM:RSP FRAME-BYTES X64ASM:>IMM8 X64CODE:ASM-SINK X64ASM:ENC-ADD-RI8
   X64ASM:R15 X64CODE:ASM-SINK X64ASM:ENC-POP  X64ASM:R14 X64CODE:ASM-SINK X64ASM:ENC-POP  X64ASM:R13 X64CODE:ASM-SINK X64ASM:ENC-POP
   X64ASM:R12 X64CODE:ASM-SINK X64ASM:ENC-POP  X64ASM:RBX X64CODE:ASM-SINK X64ASM:ENC-POP
   X64CODE:RET, ;

\ r15 = the arena and the samples in their slot, read from the band.
: SAMPLES, ( -- )
   X64ASM:RAX BAND-VA IMM,
   X64ASM:RCX X64ASM:RAX PROF-ABI:PROF-TOT X64ASM:MEM-OFF LOAD,  X64ASM:RCX AT-SAMPLES SLOT!,
   X64ASM:R15 X64ASM:RAX PROF-ABI:PROF-ARENA X64ASM:MEM-OFF LOAD, ;

: ROW-EXCL, ( -- )
   X64ASM:RCX CNT-VA IMM,  X64ASM:RAX X64ASM:RCX X64ASM:RBX CELL 0 X64ASM:MEM-IDX LOAD, ;

: ROW-INCL, ( -- )
   X64ASM:RAX X64ASM:R15 X64ASM:RBX CELL PROF-ABI:ARN-INCL X64ASM:MEM-IDX LOAD, ;

: ROW-REC, ( -- )
   X64ASM:RDI X64ASM:RBX PROF-ABI:PROF-ID-ENT SCALE,
   X64ASM:RDI X64ASM:R15 X64ASM:RDI 1 PROF-ABI:ARN-RECS X64ASM:MEM-IDX LEA, ;

\ Count every stable ID, including samples retained after its code retires.
: WORDSUM, ( -- )
   X64CODE:LBL X64CODE:LBL X64CODE:LBL {: turn:label next:label done:label :}
   X64ASM:RCX ZERO-REG,  X64ASM:RDX X64ASM:R15 PROF-ABI:ARN-IDS X64ASM:MEM-OFF LOAD,
   X64ASM:R8 ZERO-REG,  X64ASM:R9 ZERO-REG,  X64ASM:R11 CNT-VA IMM,
   turn X64CODE:LBL,
      X64ASM:RCX X64ASM:RDX CMP-REG,  X64ASM:C-AE done X64CODE:JCC,
      X64ASM:RAX X64ASM:R11 X64ASM:RCX CELL 0 X64ASM:MEM-IDX LOAD,  X64ASM:R8 X64ASM:RAX X64CODE:ASM-SINK X64ASM:ENC-ADD-RR
      X64ASM:RAX X64ASM:R15 X64ASM:RCX CELL PROF-ABI:ARN-INCL X64ASM:MEM-IDX X64CODE:ASM-SINK X64ASM:ENC-OR-RM
      X64ASM:C-E next X64CODE:JCC,  X64ASM:R9 INC,
   next X64CODE:LBL,  X64ASM:RCX INC,  turn X64CODE:JMP,
   done X64CODE:LBL,  X64ASM:R8 AT-WORDS SLOT!,  X64ASM:R9 AT-ATTR SLOT!, ;

\ A header field: the text, then the value in one column, from the frame, the
\ band or the arena.
: FRAME-FIELD, ( str n -- ) {: t:str off:n :}
   t SAY,  X64ASM:RAX off SLOT@,  1 NUM, ;
: BAND-FIELD, ( str n -- ) {: t:str off:n :}
   t SAY,  X64ASM:RAX BAND-VA IMM,  X64ASM:RAX X64ASM:RAX off X64ASM:MEM-OFF LOAD,  1 NUM, ;
: ARENA-FIELD, ( str n -- ) {: t:str off:n :}
   t SAY,  X64ASM:RAX X64ASM:R15 off X64ASM:MEM-OFF LOAD,  1 NUM, ;
\ The deferred slots' summed weights, from r15 = arena: the twin of prof.f C-PROF-DEFER-WEIGHT.
: DEFER-FIELD, ( str -- ) {: t:str :}
   X64CODE:LBL X64CODE:LBL {: turn:label done:label :}
   t SAY,
   X64ASM:RAX ZERO-REG,  X64ASM:RCX X64ASM:R15 PROF-ABI:ARN-DEFER X64ASM:MEM-OFF LOAD,
   X64ASM:RDX X64ASM:R15 PROF-ABI:ARN-DEF PROF-ABI:PROF-SLOT-WEIGHT + X64ASM:MEM-OFF LEA,
   turn X64CODE:LBL,
      X64ASM:RCX TEST,  X64ASM:C-E done X64CODE:JCC,
      X64ASM:RAX X64ASM:RDX X64ASM:MEM-AT X64CODE:ASM-SINK X64ASM:ENC-ADD-RM
      X64ASM:RDX PROF-ABI:PROF-DEFER-ENT ADDI,  X64ASM:RCX DEC,  turn X64CODE:JMP,
   done X64CODE:LBL,  1 NUM, ;

\ The header: words + other + new + defer + spill + foreign == samples is the
\ identity it states; foreign charged to callers is a share of words. After a
\ sync, defer is 0 and new holds the deferred samples whose pc belongs to no
\ live record; the limit's dump does not sync.
: HEAD, ( bool -- ) {: json:bool :}
   json if s\" {\"samples\":" else s" profiler samples " then AT-SAMPLES FRAME-FIELD,
   json if s\" ,\"words\":" else s"  words " then AT-WORDS FRAME-FIELD,
   json if s\" ,\"other\":" else s"  other " then PROF-ABI:PROF-OTHER BAND-FIELD,
   json if s\" ,\"new\":" else s"  new " then PROF-ABI:ARN-NEW ARENA-FIELD,
   json if s\" ,\"defer\":" else s"  defer " then DEFER-FIELD,
   json if s\" ,\"spill\":" else s"  spill " then PROF-ABI:ARN-SPILL ARENA-FIELD,
   json if s\" ,\"foreign\":" else s"  foreign " then PROF-ABI:PROF-FOREIGN BAND-FIELD,
   json if s\" ,\"foreign charged to callers\":" else s"  foreign charged to callers " then
   PROF-ABI:ARN-FCALLED ARENA-FIELD,
   json if s\" ,\"frames\":" else s"  frames " then PROF-ABI:ARN-FRAMES ARENA-FIELD,
   json if s\" ,\"dropped\":" else s"  dropped " then PROF-ABI:ARN-DROP ARENA-FIELD,
   json if s\" ,\"indexed\":" else s"  indexed " then PROF-ABI:ARN-COUNT ARENA-FIELD,
   json if s\" ,\"usec\":" else s"  usec " then PROF-ABI:ARN-USEC ARENA-FIELD,
   json if s\" ,\"attributed\":" else s"  attributed " then AT-ATTR FRAME-FIELD,
   json if exit then
   NL, ;

\ One text row: exclusive, its share, inclusive, its share, then the word.
: REP-ROW, ( -- )
   X64ASM:RAX AT-EXCL SLOT@,  COLS NUM,
   X64ASM:RAX AT-EXCL SLOT@,  X64ASM:R8 AT-SAMPLES SLOT@,  PCT-LBL X64CODE:CALL,
   ROW-INCL,  COLS NUM,
   ROW-INCL,  X64ASM:R8 AT-SAMPLES SLOT@,  PCT-LBL X64CODE:CALL,
   s"   " SAY,
   ROW-REC,  NAMED,
   NL, ;

\ rax = the record behind the caller index in r9, or 0 for PROF-CALLER-NONE,
\ which stands for a sample the walk could not attribute and owns no row.
: CALLER-REC, ( -- )
   X64CODE:LBL X64CODE:LBL {: none:label done:label :}
   X64ASM:R9 PROF-ABI:PROF-CALLER-NONE X64ASM:>IMM32 X64CODE:ASM-SINK X64ASM:ENC-CMP-RI32  X64ASM:C-E none X64CODE:JCC,
   X64ASM:RAX X64ASM:R9 PROF-ABI:PROF-ID-ENT SCALE,
   X64ASM:RCX X64ASM:R15 PROF-ABI:ARN-RECS X64ASM:MEM-OFF LEA,  X64ASM:RAX X64ASM:RCX X64CODE:ASM-SINK X64ASM:ENC-ADD-RR
   done X64CODE:JMP,
   none X64CODE:LBL,  X64ASM:RAX ZERO-REG,
   done X64CODE:LBL, ;

\ rdi = a record or 0: its qualified name, or (unknown).
: CALLER-NAME, ( -- )
   X64CODE:LBL X64CODE:LBL {: none:label done:label :}
   X64ASM:RDI TEST,  X64ASM:C-E none X64CODE:JCC,
   NAMED,  done X64CODE:JMP,
   none X64CODE:LBL,  s" (unknown)" SAY,
   done X64CODE:LBL, ;

\ One caller line: r9 = the caller's record index, r8 = the edge count, and its
\ share of the row's own denominator, whose reason prof.f C-PROF-REP-CALLER
\ gives.
: REP-CALLER, ( -- )
   CALLER-REC,  X64ASM:RAX AT-REC SLOT!,  X64ASM:R8 AT-N SLOT!,
   s"          <- " SAY,
   X64ASM:RAX AT-N SLOT@,  COLS NUM,
   X64ASM:RAX AT-N SLOT@,  X64ASM:R8 AT-DENOM SLOT@,  PCT-LBL X64CODE:CALL,
   s"  " SAY,
   X64ASM:RDI AT-REC SLOT@,  CALLER-NAME,
   NL, ;

\ The row's top callers: at most PROF-CALLERS passes over the edge table, each
\ taking the largest count below the one before it, or the same count at a
\ later slot.
: REP-CALLERS, ( -- )
   X64CODE:LBL X64CODE:LBL X64CODE:LBL X64CODE:LBL X64CODE:LBL {: rank:label scan:label next:label scanned:label done:label :}
   X64CODE:LBL {: tie:label :}
   X64ASM:RAX ZERO-REG,  X64ASM:RAX AT-RANK SLOT!,
   X64ASM:RAX ALL-ONES,  X64ASM:RAX AT-CAP SLOT!,  X64ASM:RAX AT-CAP-SLOT SLOT!,      \ nothing printed yet
   rank X64CODE:LBL,
      X64ASM:RAX AT-RANK SLOT@,  X64ASM:RAX PROF-ABI:PROF-CALLERS X64ASM:>IMM8 X64CODE:ASM-SINK X64ASM:ENC-CMP-RI8  X64ASM:C-AE done X64CODE:JCC,
      X64ASM:R8 ZERO-REG,  X64ASM:R9 ZERO-REG,                                 \ the best count, its caller
      X64ASM:RCX X64ASM:R15 PROF-ABI:ARN-CALL X64ASM:MEM-OFF LEA,  X64ASM:RDX PROF-ABI:PROF-CALL-SLOTS IMM32,
      X64ASM:R11 AT-CAP SLOT@,
      scan X64CODE:LBL,
         X64ASM:RDX TEST,  X64ASM:C-E scanned X64CODE:JCC,
         X64ASM:RAX X64ASM:RCX X64ASM:MEM-AT LOAD,  X64ASM:RAX TEST,  X64ASM:C-E next X64CODE:JCC,
         X64ASM:RAX DEC,  X64ASM:RSI X64ASM:RAX COPY,  X64ASM:RSI PROF-ABI:PROF-REC-BITS X64ASM:>IMM8 X64CODE:ASM-SINK X64ASM:ENC-SHR-RI8
         X64ASM:RSI X64ASM:RBX CMP-REG,  X64ASM:C-NE next X64CODE:JCC,                        \ another word's edge
         X64ASM:RAX PROF-ABI:PROF-REC-MASK X64ASM:>IMM32 X64CODE:ASM-SINK X64ASM:ENC-AND-RI32
         X64ASM:RDI X64ASM:RCX CELL X64ASM:MEM-OFF LOAD,
         X64ASM:RDI X64ASM:R11 CMP-REG,  X64ASM:C-A next X64CODE:JCC,                         \ above the cap: printed
         X64ASM:C-NE tie X64CODE:JCC,
         X64ASM:RSI AT-CAP-SLOT SLOT@,
         X64ASM:RCX X64ASM:RSI CMP-REG,  X64ASM:C-BE next X64CODE:JCC,                        \ the cap's slot itself, or before it
         tie X64CODE:LBL,
         X64ASM:RDI X64ASM:R8 CMP-REG,  X64ASM:C-BE next X64CODE:JCC,                         \ same count, later slot: keep the first
         X64ASM:R8 X64ASM:RDI COPY,  X64ASM:R9 X64ASM:RAX COPY,  X64ASM:R10 X64ASM:RCX COPY,
      next X64CODE:LBL,  X64ASM:RCX PROF-ABI:PROF-CALL-ENT ADDI,  X64ASM:RDX DEC,  scan X64CODE:JMP,
      scanned X64CODE:LBL,
      X64ASM:R8 TEST,  X64ASM:C-E done X64CODE:JCC,                                    \ no caller edge left
      X64ASM:R8 AT-CAP SLOT!,  X64ASM:R10 AT-CAP-SLOT SLOT!,
      REP-CALLER,
      X64ASM:RAX AT-RANK SLOT@,  X64ASM:RAX INC,  X64ASM:RAX AT-RANK SLOT!,
      rank X64CODE:JMP,
   done X64CODE:LBL, ;

\ RCX is a stable profile ID; R9 receives its ranking count. Clobbers R11.
: RANK, ( bool -- ) {: incl:bool :}
   incl if
      X64ASM:R9 X64ASM:R15 X64ASM:RCX CELL PROF-ABI:ARN-INCL X64ASM:MEM-IDX LOAD,
      exit
   then
   X64ASM:R11 CNT-VA IMM,  X64ASM:R9 X64ASM:R11 X64ASM:RCX CELL 0 X64ASM:MEM-IDX LOAD, ;

\ Select descending counts without changing them; the lower ID wins ties.
: SECTION, ( bool -- ) {: incl:bool :}
   X64CODE:LBL X64CODE:LBL X64CODE:LBL X64CODE:LBL {: row:label sel:label tie:label skip:label :}
   X64CODE:LBL X64CODE:LBL X64CODE:LBL {: take:label chosen:label done:label :}
   X64ASM:R13 ALL-ONES,  X64ASM:R14 ALL-ONES,  X64ASM:R12 ZERO-REG,
   row X64CODE:LBL,
      X64ASM:R8 ZERO-REG,  X64ASM:RBX ALL-ONES,
      X64ASM:RCX ZERO-REG,  X64ASM:RDX X64ASM:R15 PROF-ABI:ARN-IDS X64ASM:MEM-OFF LOAD,
      sel X64CODE:LBL,
         X64ASM:RCX X64ASM:RDX CMP-REG,  X64ASM:C-AE chosen X64CODE:JCC,
         incl RANK,
         X64ASM:R9 TEST,  X64ASM:C-E skip X64CODE:JCC,
         X64ASM:R9 X64ASM:R13 CMP-REG,  X64ASM:C-A skip X64CODE:JCC,                          \ above the threshold: printed
         X64ASM:C-NE tie X64CODE:JCC,
         X64ASM:RCX X64ASM:R14 CMP-REG,  X64ASM:C-BE skip X64CODE:JCC,                        \ the threshold row itself, or before it
         tie X64CODE:LBL,
         X64ASM:R9 X64ASM:R8 CMP-REG,  X64ASM:C-A take X64CODE:JCC,
         X64ASM:C-NE skip X64CODE:JCC,
         X64ASM:RCX X64ASM:RBX CMP-REG,  X64ASM:C-AE skip X64CODE:JCC,                        \ the same count later: keep the first
         take X64CODE:LBL,
         X64ASM:R8 X64ASM:R9 COPY,  X64ASM:RBX X64ASM:RCX COPY,
      skip X64CODE:LBL,  X64ASM:RCX INC,  sel X64CODE:JMP,
      chosen X64CODE:LBL,
      X64ASM:R8 TEST,  X64ASM:C-E done X64CODE:JCC,                                    \ no counted row left
      X64ASM:R13 X64ASM:R8 COPY,  X64ASM:R14 X64ASM:RBX COPY,
      ROW-EXCL,  X64ASM:RAX AT-EXCL SLOT!,
      incl if ROW-INCL, then  X64ASM:RAX AT-DENOM SLOT!,
      REP-ROW,
      REP-CALLERS,
      X64ASM:R12 INC,
      X64ASM:R12 PROF-ABI:PROF-ROWS X64ASM:>IMM8 X64CODE:ASM-SINK X64ASM:ENC-CMP-RI8  X64ASM:C-B row X64CODE:JCC,
   done X64CODE:LBL, ;

\ Include every ID either count reached, even after its code retires.
: JSON-ROWS, ( -- )
   X64CODE:LBL X64CODE:LBL X64CODE:LBL X64CODE:LBL {: turn:label first:label next:label done:label :}
   s\" ,\"rows\":[" SAY,
   X64ASM:R12 ZERO-REG,
   X64ASM:RBX ZERO-REG,  X64ASM:R13 X64ASM:R15 PROF-ABI:ARN-IDS X64ASM:MEM-OFF LOAD,
   turn X64CODE:LBL,
      X64ASM:RBX X64ASM:R13 CMP-REG,  X64ASM:C-AE done X64CODE:JCC,
      ROW-EXCL,  X64ASM:RAX AT-EXCL SLOT!,
      ROW-INCL,  X64ASM:RAX X64ASM:RSP AT-EXCL X64ASM:MEM-OFF X64CODE:ASM-SINK X64ASM:ENC-OR-RM
      X64ASM:C-E next X64CODE:JCC,                                              \ neither count moved: no row
      X64ASM:R12 TEST,  X64ASM:C-E first X64CODE:JCC,  s" ," SAY,
      first X64CODE:LBL,  X64ASM:R12 1 IMM32,
      s\" {\"word\":\"" SAY,
      ROW-REC,  NAMED,
      DQ,  s\" ,\"excl\":" SAY,
      X64ASM:RAX AT-EXCL SLOT@,  1 NUM,
      s\" ,\"incl\":" SAY,
      ROW-INCL,  1 NUM,
      s" }" SAY,
   next X64CODE:LBL,  X64ASM:RBX INC,  turn X64CODE:JMP,
   done X64CODE:LBL,
   s" ]" SAY, ;

\ r9 = a record index or PROF-CALLER-NONE: its name as a JSON string body.
: JSON-NAME, ( -- )  CALLER-REC,  X64ASM:RDI X64ASM:RAX COPY,  CALLER-NAME, ;

\ Every caller edge, in slot order, flat rather than under its row.
