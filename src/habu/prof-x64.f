   X64ASM:RDI CLOCK-MONOTONIC IMM32,  X64ASM:RSI X64ASM:RSP COPY,  NR-CLOCK-GETTIME SYS,
   X64ASM:RAX X64ASM:RSP X64ASM:MEM-AT LOAD,  X64ASM:RAX X64ASM:RAX NS-PER-SEC X64ASM:>IMM32 X64CODE:ASM-SINK X64ASM:ENC-IMUL-RRI32
   X64ASM:RAX X64ASM:RSP CELL X64ASM:MEM-OFF X64CODE:ASM-SINK X64ASM:ENC-ADD-RM
   X64ASM:RSP X64ASM:RSP 16 X64ASM:MEM-OFF LEA,
   X64ASM:RDI X64CODE:ASM-SINK X64ASM:ENC-POP  X64ASM:RSI X64CODE:ASM-SINK X64ASM:ENC-POP ;

\ FIND ( rdi = pc, rsi = arena -- rax = index entry or 0 ): the twin of prof.f
\ LPROFFIND, the whole of pc attribution, shared by the handler and by
\ prof-pc>rec, so the row answers what a tick counts: the entry with the
\ greatest start <= pc, when pc lies below its end. Bounded: one range test
\ and at most log2(DICT-CAP) = 16 compares. Clobbers rcx rdx r8 r9 and the
\ flags; rdi and rsi survive.
: FIND-HELPER, ( -- )
   FIND-LBL X64CODE:LBL,
   X64CODE:LBL X64CODE:LBL X64CODE:LBL X64CODE:LBL X64CODE:LBL {: halve:label upper:label found:label miss:label out:label :}
   X64ASM:RCX X64ASM:RSI PROF-ABI:ARN-COUNT X64ASM:MEM-OFF LOAD,  X64ASM:RCX TEST,  X64ASM:C-E miss X64CODE:JCC,     \ hi = the entry count
   X64ASM:RDI X64ASM:RSI PROF-ABI:ARN-LO X64ASM:MEM-OFF CMP-MEM,  X64ASM:C-B miss X64CODE:JCC,                \ below every span
   X64ASM:RDI X64ASM:RSI PROF-ABI:ARN-HI X64ASM:MEM-OFF CMP-MEM,  X64ASM:C-AE miss X64CODE:JCC,               \ at or above every span
   X64ASM:RDX ZERO-REG,                                                 \ lo
   halve X64CODE:LBL,                                                    \ the rightmost entry with start <= pc
      X64ASM:RDX X64ASM:RCX CMP-REG,  X64ASM:C-AE found X64CODE:JCC,
      X64ASM:R8 X64ASM:RDX X64ASM:RCX 1 0 X64ASM:MEM-IDX LEA,  X64ASM:R8 1 X64ASM:>IMM8 X64CODE:ASM-SINK X64ASM:ENC-SHR-RI8   \ mid = (lo + hi) / 2
      X64ASM:R9 X64ASM:R8 PROF-ABI:PROF-ENT SCALE,
      X64ASM:R9 X64ASM:RSI X64ASM:R9 1 PROF-ABI:ARN-IDX PROF-ABI:ENT-START + X64ASM:MEM-IDX LOAD,
      X64ASM:R9 X64ASM:RDI CMP-REG,  X64ASM:C-A upper X64CODE:JCC,                            \ start > pc: mid is the new hi
      X64ASM:RDX X64ASM:R8 1 X64ASM:MEM-OFF LEA,  halve X64CODE:JMP,
   upper X64CODE:LBL,  X64ASM:RCX X64ASM:R8 COPY,  halve X64CODE:JMP,
   found X64CODE:LBL,
   X64ASM:RDX TEST,  X64ASM:C-E miss X64CODE:JCC,                                      \ every start is above the pc
   X64ASM:RAX X64ASM:RDX PROF-ABI:PROF-ENT SCALE,
   X64ASM:RAX X64ASM:RSI X64ASM:RAX 1 PROF-ABI:ARN-IDX PROF-ABI:PROF-ENT - X64ASM:MEM-IDX LEA,                 \ entry lo - 1
   X64ASM:RDI X64ASM:RAX PROF-ABI:ENT-END X64ASM:MEM-OFF CMP-MEM,  X64ASM:C-B out X64CODE:JCC,                \ else the pc sits in a gap above it
   miss X64CODE:LBL,  X64ASM:RAX ZERO-REG,
   out X64CODE:LBL,  X64CODE:RET, ;

\ EDGE ( rsi = arena, rdi = the sampled record, rdx = its caller's, the
\ caller's [rsp] = the weight ): the twin of prof.f LPROFEDGE, the weight added
\ to one caller edge in the open-addressed table, keyed (sampled <<
\ PROF-REC-BITS | caller) + 1 as there. A sample whose own record is unknown
\ (rdi < 0) has no edge to key, and a full probe window counts the weight as
\ dropped rather than overwriting another pair. Clobbers rax rcx r8-r11 and
\ the flags; rsi, rdi and rdx survive.
: EDGE-HELPER, ( -- )
   EDGE-LBL X64CODE:LBL,
   X64CODE:LBL X64CODE:LBL X64CODE:LBL X64CODE:LBL {: probe:label free:label hit:label done:label :}
   X64ASM:RDI TEST,  X64ASM:C-S done X64CODE:JCC,
   X64ASM:RAX X64ASM:RDI COPY,  X64ASM:RAX PROF-ABI:PROF-REC-BITS X64ASM:>IMM8 X64CODE:ASM-SINK X64ASM:ENC-SHL-RI8
   X64ASM:RAX X64ASM:RDX X64CODE:ASM-SINK X64ASM:ENC-OR-RR  X64ASM:RAX INC,                          \ the key, never 0
   X64ASM:RCX PROF-ABI:PROF-HASH IMM,  X64ASM:RCX X64ASM:RAX X64CODE:ASM-SINK X64ASM:ENC-IMUL-RR
   X64ASM:RCX HASH-SHIFT X64ASM:>IMM8 X64CODE:ASM-SINK X64ASM:ENC-SHR-RI8                     \ its first slot
   X64ASM:R8 X64ASM:RSI PROF-ABI:ARN-CALL X64ASM:MEM-OFF LEA,
   X64ASM:R9 PROF-ABI:PROF-CALL-PROBE IMM32,
   probe X64CODE:LBL,
      X64ASM:R10 X64ASM:RCX PROF-ABI:PROF-CALL-ENT SCALE,  X64ASM:R10 X64ASM:R8 X64CODE:ASM-SINK X64ASM:ENC-ADD-RR
      X64ASM:R11 X64ASM:R10 X64ASM:MEM-AT LOAD,
      X64ASM:R11 TEST,  X64ASM:C-E free X64CODE:JCC,
      X64ASM:R11 X64ASM:RAX CMP-REG,  X64ASM:C-E hit X64CODE:JCC,
      X64ASM:RCX INC,  X64ASM:RCX PROF-ABI:PROF-CALL-MASK X64ASM:>IMM32 X64CODE:ASM-SINK X64ASM:ENC-AND-RI32
      X64ASM:R9 DEC,  X64ASM:C-NE probe X64CODE:JCC,
   X64ASM:R11 CELL WEIGHT,  X64ASM:R11 X64ASM:RSI PROF-ABI:ARN-DROP ADD-MEM,  done X64CODE:JMP,
   free X64CODE:LBL,  X64ASM:RAX X64ASM:R10 X64ASM:MEM-AT STORE,  X64ASM:R11 CELL WEIGHT,  X64ASM:R11 X64ASM:R10 CELL X64ASM:MEM-OFF STORE,  done X64CODE:JMP,
   hit X64CODE:LBL,  X64ASM:R11 CELL WEIGHT,  X64ASM:R11 X64ASM:R10 CELL ADD-MEM,
   done X64CODE:LBL,  X64CODE:RET, ;

: REJECTED, ( str -- ) {: t:str :}
